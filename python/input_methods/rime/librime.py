# --- per-application profile overrides (#403) ---------------------------
# The profile key holding the per-application maps, and the rime options those
# maps may pin for this process. Values are read with RimeConfigGetBool, so a
# non-bool or an unknown key simply is not found and changes nothing.
APP_OPTIONS_PATH = "app_options"
APP_OPTION_KEYS = (b"ascii_mode", b"full_shape", b"ascii_punct")


def rimeAppOptionNames(appname="PIME"):
    """The ``app_options`` keys tried for this process, most specific first.

    The python backend is one process serving every client, so the names come
    from it: the executable's own file name lower-cased (the form the shipped
    example uses, ``python.exe`` for the bundled interpreter, like the
    ``cmd.exe``/``notepad.exe`` form of the weasel profiles), then the engine
    application name ``Rime.<app>``, then the profile name itself. Matching is
    the config API's own, so a name is compared exactly as written in the
    profile.
    """
    names = []
    if sys.executable:
        names.append(os.path.basename(sys.executable).lower())
    names.extend(["%s.%s" % (RIME, appname), appname])
    ordered = []
    for name in names:
        if name and name not in ordered:
            ordered.append(name)
    return tuple(ordered)


def rimeApplyAppOptions(session_id, config, appname="PIME"):
    """Push this process's ``app_options`` onto a live session (#403).

    Reads ``app_options/<name>/<key>`` for every candidate name and each of
    ``APP_OPTION_KEYS``, first match wins per key, and sets the option with
    ``RimeSetOption`` so the session's initial mode is the declared one. Unknown
    keys, non-bool values and a missing block are ignored. Returns the number of
    options applied.
    """
    if not session_id:
        return 0
    applied = 0
    settled = set()
    for name in rimeAppOptionNames(appname):
        for key in APP_OPTION_KEYS:
            if key in settled:
                continue
            value = c_int()
            path = "%s/%s/%s" % (APP_OPTIONS_PATH, name, key.decode("utf-8"))
            if not rime.config_get_bool(config, path.encode("UTF-8"), value):
                continue
            rime.set_option(session_id, key, bool(value.value))
            settled.add(key)
            applied += 1
    return applied


def rimeApplyProfileOptions(session_id, appname="PIME"):
    """Apply the named profile's ``app_options`` to a fresh session (#403).

    Opens ``<appname>.yaml`` for the read and closes it again; called once per
    new session from ``RimeTextService.createSession``, so a later tray-menu
    rebuild leaves the options the user toggled at runtime alone.
    """
    config = RimeConfig()
    if not rime.config_open(appname.encode("UTF-8"), config):
        return 0
    try:
        return rimeApplyAppOptions(session_id, config, appname)
    finally:
        rime.config_close(config)


def rimeSelectSchema(session_id, schema_id):
    rime.select_schema(session_id, schema_id)
    user_config = RimeConfig()
    if rime.config_open(b'user', user_config):
        rime.config_set_string(user_config, b'var/previously_selected_schema', schema_id)
        rime.config_set_int(user_config, b'var/schema_access_time/' + schema_id, c_int(int(time())))
        rime.config_close(user_config)


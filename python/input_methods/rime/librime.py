# --- bounded retention for the rime path (#445) --------------------------
# Values quoted in the module docstring; the tests read them from here.
RIME_LOG_MAX_FILES = 9      # three glog levels, three starts
SYNC_SNAPSHOT_MAX = 3       # newest sync/<user id> folders kept
PRUNE_SCAN_LIMIT = 512      # directory entries inspected per pass

# Set by rimeInit so a re-import in the same process does not re-initialize a
# live engine; the direct finalize()/initialize(None) pair of the deploy
# command is unaffected.
_rime_started = False


def _aged_entries(directory, prefix="", limit=PRUNE_SCAN_LIMIT,
                  dirs_only=False):
    """One walk of `directory`; return ``(matched_total, newest_rows)``.

    `newest_rows` holds the newest `limit` ``(mtime, name, path)`` tuples of the
    entries whose name starts with `prefix`, oldest first, kept in a heap of
    `limit` items; `matched_total` counts every match of the single walk, so a
    caller can tell a full listing from a capped window and repeat the walk when
    the directory was larger than the cap. `dirs_only` restricts the match to
    directories, which is what the folder-pruning caller needs: stray files in
    the same directory then neither count nor compete for the window.
    """
    matched = 0

    def rows():
        nonlocal matched
        try:
            with os.scandir(directory) as it:
                for entry in it:
                    name = entry.name
                    if prefix and not name.startswith(prefix):
                        continue
                    try:
                        is_dir = entry.is_dir()
                        mtime = entry.stat().st_mtime
                    except OSError:
                        continue  # vanished between the listing and the stat
                    if dirs_only and not is_dir:
                        continue
                    matched += 1
                    yield (mtime, name, entry.path)
        except OSError:
            return  # no such directory yet: the pass is a no-op

    found = list(heapq.nlargest(limit, rows()))
    found.reverse()  # oldest first, so callers drop the leading entries
    return matched, found


def _prune(scan, keep, remover):
    """Delete all but the newest `keep` matches; return ``(before, after)``.

    `scan` is a zero-argument call giving ``(matched_total, newest_rows)``. A
    walk that fills the cap is repeated until one comes back short, so the
    survivor set is the newest `keep` even for a directory larger than
    ``PRUNE_SCAN_LIMIT``.
    """
    total, rows = scan()
    before = total
    deleted = 0
    while True:
        for _mtime, _name, path in rows[:max(len(rows) - keep, 0)]:
            try:
                remover(path)
                deleted += 1
            except OSError:
                pass
        if total < PRUNE_SCAN_LIMIT:
            break  # this walk already covered the whole directory
        previous = total
        total, rows = scan()
        if total == previous:
            break  # the rescans agree: a cap-sized listing that never shrinks
    return (before, before - deleted)


def prune_log_files(log_dir, app_name="PIME", keep=RIME_LOG_MAX_FILES):
    """Bound the engine's glog files in `log_dir`.

    Only files named ``Rime.<app_name>.log.*`` are considered; the numbered
    survivors are the newest by modification time. Returns the ``(before,
    after)`` file counts of that set.
    """
    prefix = "%s.%s." % (RIME, app_name)
    return _prune(lambda: _aged_entries(log_dir, prefix), keep, os.remove)


def prune_sync_snapshots(user_dir, keep=SYNC_SNAPSHOT_MAX):
    """Bound the sync snapshots of `user_dir` to the newest `keep` folders.

    Returns the ``(before, after)`` folder counts of ``<user_dir>/sync``.
    """
    return _prune(lambda: _aged_entries(os.path.join(user_dir, "sync"),
                                        dirs_only=True),
                  keep, shutil.rmtree)


def prune_rime_user_data(user_dir, app_name="PIME", log_dir=None):
    """Run every bounded retention pass once; return the measured counts.

    `log_dir` defaults to the directory the engine itself writes to and that the
    tray menu opens (``%TEMP%`` on Windows). Calling it twice on the same
    directories is a no-op for the second pass.
    """
    if log_dir is None:
        log_dir = tempdir()
    log_before, log_after = prune_log_files(log_dir, app_name=app_name)
    sync_before, sync_after = prune_sync_snapshots(user_dir)
    return {
        "log_before": log_before,
        "log_after": log_after,
        "sync_before": sync_before,
        "sync_after": sync_after,
    }


def rimeInit(datadir="data", userdir="data", fullcheck=True, appname="python", appver="0.01"):
    global _rime_started
    traits = RimeTraits(
        shared_data_dir=c_char_p(datadir.encode(ENC)),
        user_data_dir=c_char_p(userdir.encode(ENC)),
        distribution_name=c_char_p(RIME.encode("UTF-8")),
        distribution_code_name=c_char_p(appname.encode("UTF-8")),
        distribution_version=c_char_p(appver.encode("UTF-8")),
        app_name=c_char_p(("%s.%s"%(RIME, appname)).encode("UTF-8"))
        )
    # Measured against the bundled rime.dll: RimeSetup answers on the first call
    # and a repeated one aborts on glog's "Could not create logging file", so
    # both the traits and the one-shot start-up sit behind the guard; the direct
    # finalize()/initialize(None) pair of the deploy command is unaffected.
    if not _rime_started:
        rime.setup(traits)
        #cb = RimeNotificationHandler(rimeNotificationHandler)
        #rime.set_notification_handler(cb, byref(rime))
        rime.initialize(None)
        if rime.start_maintenance(fullcheck):
            rime.join_maintenance_thread()
        _rime_started = True
    # Both directories are known here, so this is the one place the bounded
    # retention pass of #445 runs: on backend start, after the engine is up.
    prune_rime_user_data(userdir, app_name=appname)


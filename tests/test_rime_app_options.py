"""#403: the rime profile's ``app_options`` reaches the engine's initial mode.

The rime profile may carry a per-application block, e.g.

    app_options:
      python.exe:
        ascii_mode: true

``python/input_methods/rime/librime.py`` reads it through the rime config API
and pushes the honoured keys onto the freshly created session with
``RimeSetOption``, so the first key press is already in the declared mode.
Anything else in the map is ignored; a profile without the key, a profile whose
entries are commented out, and unknown keys all leave the engine defaults alone
and startup intact.

The assertions are made at the engine seam: a session id from ``RimeCreateSession``
plus a config built with ``RimeConfigInit``/``RimeConfigLoadString``, so no
deployed file is involved and the observed option value is the one librime holds.

Conventions measured against the bundled ``rime.dll`` and relied on below:
``RimeConfigGetBool`` answers only for bool nodes, so an int or an unknown key
reads as "not found" (0); ``RimeConfigBeginList`` answers for sequences only
(maps return 0), which is why the map is read by full path; path matching is
case-sensitive, so the candidate names are lower-cased from ``sys.executable``;
``RimeGetOption`` returns 0 for an option the engine does not know; and one
process sets the engine up once — ``RimeSetup`` after ``RimeFinalize`` aborts on
glog's "Could not create logging file", while a bare ``RimeInitialize`` after
``RimeFinalize`` works, which is what ``rimeInit``'s ``_rime_started`` guard
keeps the extra calls down to.

Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
SPDX-License-Identifier: LGPL-2.1-or-later
"""

import os
import sys
import tempfile
import unittest

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), os.path.pardir))
PYTHON_DIR = os.path.join(ROOT, "python")
if PYTHON_DIR not in sys.path:
    sys.path.insert(0, PYTHON_DIR)

try:
    from input_methods.rime import librime
    librime.rime  # touched by the import; fails when the library is missing
except Exception as import_error:  # pragma: no cover - Linux without librime.so
    librime = None
    IMPORT_ERROR = import_error
else:
    IMPORT_ERROR = None

APP_NAME = "PIME"
PROFILE = os.path.join(PYTHON_DIR, "input_methods", "rime", "data", "PIME.yaml")


def option(session_id, name):
    return librime.rime.get_option(session_id, name)


@unittest.skipIf(librime is None, "librime is not installed: %s" % IMPORT_ERROR)
class AppOptionsSeamTests(unittest.TestCase):
    """One engine for the whole module; the seam calls are per test."""

    @classmethod
    def setUpClass(cls):
        cls.engine = librime.rime
        # One engine for the process: later calls are a no-op for setup and only
        # re-run the bounded retention pass (see rimeInit).
        if not librime._rime_started:
            cls.user_dir = tempfile.TemporaryDirectory()
            cls.addClassCleanup(cls.user_dir.cleanup)
            librime.rimeInit(
                datadir=os.path.join(PYTHON_DIR, "input_methods", "rime", "data"),
                userdir=cls.user_dir.name,
                fullcheck=False, appname=APP_NAME, appver="0.01")

    def config_from(self, text):
        config = librime.RimeConfig()
        self.assertTrue(self.engine.config_init(config),
                        "RimeConfigInit must give a usable config")
        self.assertTrue(self.engine.config_load_string(config, text.encode("utf-8")))
        self.addCleanup(self.engine.config_close, config)
        return config

    def session(self):
        session_id = self.engine.create_session()
        self.assertTrue(bool(session_id), "the engine must hand out a session")
        self.addCleanup(self.engine.destroy_session, session_id)
        return session_id

    # --- the pass-through itself -----------------------------------------
    def test_per_app_ascii_mode_reaches_the_session(self):
        config = self.config_from(
            "config_version: \"0.05\"\n"
            "app_options:\n"
            "  %s:\n"
            "    ascii_mode: true\n" % os.path.basename(sys.executable).lower())
        session_id = self.session()
        self.assertEqual(option(session_id, b"ascii_mode"), 0,
                         "the engine starts in Chinese mode")

        applied = librime.rimeApplyAppOptions(session_id, config, APP_NAME)

        self.assertEqual(applied, 1)
        self.assertEqual(option(session_id, b"ascii_mode"), 1)

    def test_a_false_value_is_applied_and_not_just_detected(self):
        config = self.config_from(
            "config_version: \"0.05\"\n"
            "app_options:\n"
            "  %s:\n"
            "    ascii_mode: false\n" % os.path.basename(sys.executable).lower())
        session_id = self.session()
        self.engine.set_option(session_id, b"ascii_mode", True)
        self.assertEqual(option(session_id, b"ascii_mode"), 1)

        applied = librime.rimeApplyAppOptions(session_id, config, APP_NAME)

        self.assertEqual(applied, 1)
        self.assertEqual(option(session_id, b"ascii_mode"), 0)

    def test_every_honoured_key_is_applied(self):
        name = os.path.basename(sys.executable).lower()
        config = self.config_from(
            "config_version: \"0.05\"\n"
            "app_options:\n"
            "  %s:\n"
            "    ascii_mode: true\n"
            "    full_shape: true\n"
            "    ascii_punct: false\n" % name)
        session_id = self.session()

        applied = librime.rimeApplyAppOptions(session_id, config, APP_NAME)

        self.assertEqual(applied, len(librime.APP_OPTION_KEYS))
        self.assertEqual(option(session_id, b"ascii_mode"), 1)
        self.assertEqual(option(session_id, b"full_shape"), 1)
        self.assertEqual(option(session_id, b"ascii_punct"), 0)
        self.assertEqual(librime.APP_OPTION_KEYS,
                         (b"ascii_mode", b"full_shape", b"ascii_punct"))

    # --- tolerance --------------------------------------------------------
    def test_unknown_keys_are_ignored_without_breaking_startup(self):
        name = os.path.basename(sys.executable).lower()
        config = self.config_from(
            "config_version: \"0.05\"\n"
            "app_options:\n"
            "  %s:\n"
            "    ascii_mode: true\n"
            "    unknown_flag: 7\n"
            "    list_key:\n"
            "      - one\n"
            "      - two\n"
            "    nested:\n"
            "      deeper: true\n" % name)
        session_id = self.session()

        applied = librime.rimeApplyAppOptions(session_id, config, APP_NAME)

        self.assertEqual(applied, 1, "only the honoured keys count as applied")
        self.assertEqual(option(session_id, b"ascii_mode"), 1)
        # The unknown names never became engine options.
        self.assertEqual(option(session_id, b"unknown_flag"), 0)
        self.assertEqual(option(session_id, b"nested"), 0)
        # The session still works: a key press is processed without an error.
        self.assertIn(self.engine.process_key(session_id, ord("a"), 0), (0, 1))

    def test_a_non_bool_value_is_skipped_like_an_unknown_key(self):
        name = os.path.basename(sys.executable).lower()
        config = self.config_from(
            "config_version: \"0.05\"\n"
            "app_options:\n"
            "  %s:\n"
            "    ascii_mode: 3\n" % name)
        session_id = self.session()

        self.assertEqual(librime.rimeApplyAppOptions(session_id, config, APP_NAME), 0)
        self.assertEqual(option(session_id, b"ascii_mode"), 0)

    def test_profile_without_app_options_keeps_the_defaults(self):
        config = self.config_from(
            "config_version: \"0.05\"\n"
            "style:\n"
            "  font_point: 12\n")
        session_id = self.session()

        self.assertEqual(librime.rimeApplyAppOptions(session_id, config, APP_NAME), 0)
        self.assertEqual(option(session_id, b"ascii_mode"), 0)

    def test_no_session_is_a_no_op(self):
        config = self.config_from(
            "config_version: \"0.05\"\n"
            "app_options:\n"
            "  %s:\n"
            "    ascii_mode: true\n" % os.path.basename(sys.executable).lower())
        self.assertEqual(librime.rimeApplyAppOptions(None, config, APP_NAME), 0)

    # --- the deployed-profile path ---------------------------------------
    def test_profile_wrapper_matches_a_directly_opened_config(self):
        probe = librime.RimeConfig()
        if not self.engine.config_open(APP_NAME.encode("utf-8"), probe):
            self.engine.config_close(probe)
            self.skipTest("the engine's profile directory belongs to an earlier module")
        self.addCleanup(self.engine.config_close, probe)
        first = self.session()
        second = self.session()

        applied = librime.rimeApplyProfileOptions(first, APP_NAME)
        direct = librime.rimeApplyAppOptions(second, probe, APP_NAME)

        # The wrapper is the same read with the open/close around it.
        self.assertIsInstance(applied, int)
        self.assertLessEqual(applied, len(librime.APP_OPTION_KEYS))
        self.assertEqual(applied, direct)
        self.assertEqual(option(first, b"ascii_mode"), option(second, b"ascii_mode"))

    def test_rebuilding_the_style_keeps_the_toggled_option(self):
        probe = librime.RimeConfig()
        if not self.engine.config_open(APP_NAME.encode("utf-8"), probe):
            self.engine.config_close(probe)
            self.skipTest("the engine's profile directory belongs to an earlier module")
        self.engine.config_close(probe)
        session_id = self.session()
        self.engine.set_option(session_id, b"ascii_mode", True)

        style = librime.RimeStyle(APP_NAME, session_id)

        # RimeStyle is rebuilt on every tray-menu open; only createSession pushes
        # the per-application defaults, so the user's runtime toggle survives.
        self.assertEqual(option(session_id, b"ascii_mode"), 1)
        # config_get_menu leaves menu as None when the profile has no menu list.
        self.assertTrue(style.menu is None or isinstance(style.menu, list))

    # --- documented matching rule ----------------------------------------
    def test_candidates_are_tried_in_the_documented_order(self):
        name = os.path.basename(sys.executable).lower()
        self.assertEqual(librime.rimeAppOptionNames(APP_NAME),
                         (name, "Rime.%s" % APP_NAME, APP_NAME))
        # The most specific entry wins.
        config = self.config_from(
            "config_version: \"0.05\"\n"
            "app_options:\n"
            "  %s:\n"
            "    ascii_mode: true\n"
            "  PIME:\n"
            "    ascii_mode: false\n" % name)
        session_id = self.session()
        librime.rimeApplyAppOptions(session_id, config, APP_NAME)
        self.assertEqual(option(session_id, b"ascii_mode"), 1)

    def test_a_key_shared_only_under_the_engine_name_still_applies(self):
        config = self.config_from(
            "config_version: \"0.05\"\n"
            "app_options:\n"
            "  Rime.%s:\n"
            "    full_shape: true\n" % APP_NAME)
        session_id = self.session()

        applied = librime.rimeApplyAppOptions(session_id, config, APP_NAME)

        self.assertEqual(applied, 1)
        self.assertEqual(option(session_id, b"full_shape"), 1)

    def test_key_is_documented_in_the_module_docstring(self):
        documented = librime.__doc__ or ""
        self.assertIn("app_options", documented)
        for key in librime.APP_OPTION_KEYS:
            with self.subTest(key=key):
                self.assertIn(key.decode("utf-8"), documented)


if __name__ == "__main__":
    unittest.main()

import os
import sys
import tempfile
import time
import unittest
from unittest.mock import MagicMock

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), os.path.pardir))
PYTHON_DIR = os.path.join(ROOT, "python")
TESTS_DIR = os.path.dirname(os.path.abspath(__file__))
for path in (PYTHON_DIR, TESTS_DIR):
    if path not in sys.path:
        sys.path.insert(0, path)

import ime_smoke_runner  # noqa: E402 - located after ROOT is known
ime_smoke_runner.install_windows_shims()


@unittest.skipIf(ime_smoke_runner.under_wine(),
                 "Wine lacks propsys.dll.VariantToString, which importing cinbase reaches")
@unittest.skipUnless(ime_smoke_runner.opencc_available(),
                     "libopencc.so not installed (Debian: apt install libopencc-dev)")
class CinbaseCandidateNavigationTests(unittest.TestCase):
    def setUp(self):
        self.old_appdata = os.environ.get("APPDATA")
        self.old_cwd = os.getcwd()
        self.temp_dir = tempfile.TemporaryDirectory(prefix="pime-cin-nav-")
        os.environ["APPDATA"] = self.temp_dir.name
        os.chdir(self.temp_dir.name)

    def tearDown(self):
        os.chdir(self.old_cwd)
        if self.old_appdata is None:
            os.environ.pop("APPDATA", None)
        else:
            os.environ["APPDATA"] = self.old_appdata
        self.temp_dir.cleanup()

    @staticmethod
    def key_event(char_code, key_code=None, printable=False, oem3=False):
        event = MagicMock()
        event.charCode = char_code
        event.keyCode = char_code if key_code is None else key_code
        event.seqNum = 1
        event.repeatCount = 1
        event.scanCode = 0
        event.isExtended = False
        event.keyStates = [0] * 256
        event.isPrintableChar.return_value = printable
        event.isKeyDown.side_effect = lambda vk: vk == 0xC0 and oem3
        event.isKeyToggled.return_value = False
        return event

    def send(self, service, char_code, key_code=None, printable=False, oem3=False):
        event = self.key_event(char_code, key_code, printable, oem3)
        if service.filterKeyDown(event):
            service.onKeyDown(event)

    def activate_checj(self):
        from input_methods.checj import checj_ime

        service = checj_ime.CheCJTextService(ime_smoke_runner.FakeClient())
        service.onActivate()
        for _ in range(500):
            if checj_ime.CinTable.cin is not None and not checj_ime.CinTable.loading:
                break
            time.sleep(0.02)
        self.assertIsNotNone(checj_ime.CinTable.cin)
        return service

    def test_page_keys_clamp_and_space_wraps(self):
        service = self.activate_checj()

        # Make the fixture independent of the shipped per-page setting.
        service.candPerPage = 2
        service.candPerRow = 1
        service.candidateView.configure(2, 1)

        self.send(service, ord("z"), ord("z"))
        self.send(service, ord("b"), ord("b"))
        self.assertEqual(service.candidateView.page, 0)
        self.assertEqual(len(service.candidateList), 2)

        first_page = list(service.candidateList)
        for page in range(1, 5):
            self.send(service, 0, 0x22)  # VK_NEXT
            self.assertEqual(service.candidateView.page, page)
            self.assertEqual(service.candidateCursor, 0)
            self.assertEqual(len(service.candidateList), 2)
        self.assertNotEqual(first_page, list(service.candidateList))

        self.send(service, 0, 0x22)
        self.assertEqual(service.candidateView.page, 4)
        self.assertEqual(service.candidateCursor, 0)

        self.send(service, 0, 0x27)  # VK_RIGHT
        self.assertEqual(service.candidateCursor, 1)
        self.send(service, 0, 0x27)
        self.assertEqual((service.candidateView.page, service.candidateCursor), (4, 1))

        for page in (3, 2, 1, 0):
            self.send(service, 0, 0x21)  # VK_PRIOR
            self.assertEqual(service.candidateView.page, page)
            self.assertEqual(service.candidateCursor, 0)
        self.send(service, 0, 0x21)
        self.assertEqual((service.candidateView.page, service.candidateCursor), (0, 0))

        service.switchPageWithSpace = True
        service.canUseSpaceAsPageKey = True
        for _ in range(4):
            self.send(service, 0x20, 0x20)
        self.assertEqual(service.candidateView.page, 4)
        self.send(service, 0x20, 0x20)
        self.assertEqual((service.candidateView.page, service.candidateCursor), (0, 0))

    def test_menu_switch_restores_parent_cursor(self):
        service = self.activate_checj()

        service.candPerPage = 9
        service.candPerRow = 3
        service.candidateView.configure(9, 3)

        self.send(service, 0x60, 0xC0, oem3=True)
        self.send(service, ord("M"), ord("M"), printable=True)
        self.assertTrue(service.showmenu)
        main_items = list(service.candidateList)
        self.assertEqual(len(main_items), 7)

        # The emoji item is the last of the seven main-menu entries.
        self.send(service, 0, 0x28)
        self.send(service, 0, 0x28)
        self.assertEqual(service.candidateCursor, 6)
        self.send(service, 0, 0x0D)
        self.assertNotEqual(service.menutype, 0)
        self.assertEqual((service.candidateView.page, service.candidateCursor), (0, 0))

        self.send(service, 0, 0x08)
        self.assertEqual(service.menutype, 0)
        self.assertEqual(service.candidateCursor, 6)
        self.assertEqual(service.candidateView.page, 0)
        self.assertEqual(list(service.candidateList), main_items)
        self.assertEqual(service.candidateView.cursor, 6)

    def test_menu_selection_key_picks_the_item_it_names(self):
        service = self.activate_checj()

        service.candPerPage = 9
        service.candPerRow = 1
        service.candidateView.configure(9, 1)

        self.send(service, 0x60, 0xC0, oem3=True)
        self.send(service, ord("M"), ord("M"), printable=True)
        self.assertEqual(service.menutype, 0)
        self.assertEqual(service.candidateList[2], "功能開關")

        # "3" is the sel key of the third entry; only that entry leaves the main menu.
        self.send(service, ord("3"), ord("3"), printable=True)
        self.assertEqual(service.menutype, 1)
        self.assertEqual((service.candidateView.page, service.candidateCursor), (0, 0))
        self.assertEqual(service.candidateList[0], service.menucandidates[0])

    def test_phrase_candidates_page_through_the_view(self):
        service = self.activate_checj()

        service.candPerPage = 9
        service.candPerRow = 1
        service.candidateView.configure(9, 1)
        service.showPhrase = True

        self.send(service, ord("z"), ord("z"), printable=True)
        self.assertEqual(list(service.candidateList), ["重"])
        self.send(service, 0x20, 0x20)  # commit 重; its phrase candidates follow

        self.assertTrue(service.phrasemode)
        self.assertTrue(service.isShowPhraseCandidates)
        self.assertGreater(service.candidateView.page_count, 1)
        first_page = list(service.candidateList)
        self.assertEqual(len(first_page), 9)
        self.assertEqual((service.candidateView.page, service.candidateCursor), (0, 0))

        self.send(service, 0, 0x22)  # VK_NEXT
        self.assertEqual((service.candidateView.page, service.candidateCursor), (1, 0))
        self.assertEqual(len(service.candidateList), 9)
        self.assertNotEqual(list(service.candidateList), first_page)

        self.send(service, 0, 0x21)  # VK_PRIOR
        self.assertEqual((service.candidateView.page, service.candidateCursor), (0, 0))
        self.assertEqual(list(service.candidateList), first_page)


if __name__ == "__main__":
    unittest.main()

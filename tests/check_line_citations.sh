#!/usr/bin/env bash
# Every `path/to/file.ext:N` (or `:N-M`) citation in tracked code, tests and docs
# has to resolve: the named file must exist and, in the live material, the line(s)
# must fall inside it. The 2026-11 merge moved python/cinbase/__init__.py and left
# eight hand-quoted numbers in python/input_methods/chebihua/table_loaders.py past
# the new ends, so the review had to re-derive every one by grep; this gate makes
# that drift a red step instead of a round trip.
#
# Two ranks of file, because they age differently:
#   - live material (python/, tests/, docs/agents/, GLOSSARY.md, HACKING.txt) is
#     read as the current contract, so both halves are checked: the target exists
#     and the range sits inside it. An in-range number that lands one line off is
#     still the reviewer's to check — see the rule "A quoted line must be the line
#     the implementer wrote" in docs/agents/code-review.md.
#   - dated snapshots (docs/research/*.md, the census notes that carry their own
#     date) quote the numbering of their own reading, which a later refactor
#     legitimately moves; there only the target's existence is pinned.
#
# A name is read from the repo root first, then by unique suffix among every
# tracked file (`serviceManager.py:87`, `AsyncConnector.cpp:268` and
# `cinbase/__init__.py:515` are how the docstrings already write it); a name
# matching two tracked files is reported as ambiguous. A bare `:N` continues the
# file named on the same line, matching how a docstring pairs two ranges of one
# file. One awk process scans the tree. The self-test of this gate is read for
# nothing: the names it writes live in the sandbox repo that test builds.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later
#
# Exit codes: 0 every citation resolved, 1 a citation is broken,
# 125 not applicable (not inside a git checkout, or no citation anywhere).

set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  line citations (not inside a git checkout)\n'
    exit 125
}
cd "$ROOT" || exit 1

# The two name lists go to plain files next to the checkout: a native awk maps a
# /tmp argument differently from this shell, so both sides get the same string.
all_list=".pime-citations-all.$$"
scan_list=".pime-citations-scan.$$"
trap 'rm -f "$all_list" "$scan_list"' EXIT

# Resolution reaches the whole tracked tree (PIMETextService/, node/, go-backend/,
# installer/ included) while the scan covers the material that carries citations.
git ls-files > "$all_list"
# Only regular files become awk inputs: a directory argument is a warning and a
# skipped record (python/input_methods/rime/brise is the tracked submodule mount).
while IFS= read -r name; do
    [ -f "$name" ] && printf '%s\n' "$name" >> "$scan_list"
done < <(git ls-files -- python tests docs GLOSSARY.md HACKING.txt)

mapfile -t files < "$scan_list"
[ "${#files[@]}" -gt 0 ] || {
    printf 'SKIP  line citations (no tracked file to scan)\n'
    exit 125
}

awk '
function is_silent(p) {
    return (p ~ /^libchewing\// || p ~ /^python\/python3\// ||
            p ~ /^python\/opencc\// || p ~ /^python\/libchewing\//)
}
function is_dated(f) {
    return index(f, "docs/research/") == 1
}
# Line count of p, or -1 when p yields no line (missing or empty). An unwrapped
# final line still counts, so quoting the last line is not a false red.
function lines_of(p,    n, l, r) {
    if (p in CACHE) return CACHE[p]
    n = 0
    while (1) { r = getline l < p; if (r <= 0) break; n++ }
    close(p)
    CACHE[p] = (n == 0 ? -1 : n)
    return CACHE[p]
}
# Repo-root path for a citation name: exact, then unique suffix; "" when absent,
# the number of matches left in AMB.
function resolve(p,    i, f, hits, cand) {
    if (p in RES) return RES[p]
    if (lines_of(p) >= 0) { RES[p] = p; AMB[p] = 1; return p }
    hits = 0
    cand = ""
    for (i = 1; i <= n_all; i++) {
        f = NAME[i]
        if (f == p) { hits = 1; cand = f; break }
        if (length(f) > length(p) && substr(f, length(f) - length(p)) == "/" p) { hits++; cand = f }
    }
    AMB[p] = hits
    RES[p] = (hits == 1 ? cand : "")
    return RES[p]
}
# One range lo[-hi] against the citation name; 0 when it resolves.
function check(name, lo, hi,    p, n) {
    checked++
    if (is_silent(name)) return 0
    p = resolve(name)
    # resolve fills AMB, so the count is only meaningful after that call.
    if (AMB[name] + 0 > 1) {
        printf("ambiguous citation: %s -> %s (%d tracked files share that name)\n", FILENAME, name, AMB[name])
        return 1
    }
    if (p == "") {
        printf("broken citation: %s -> %s:%s (no such file)\n", FILENAME, name, lo)
        return 1
    }
    # A dated snapshot pins its target only; see the header.
    if (is_dated(FILENAME)) return 0
    n = lines_of(p)
    if (lo + 0 < 1 || lo + 0 > n || hi + 0 > n) {
        printf("broken citation: %s -> %s:%s-%s (%s has %d line(s))\n", FILENAME, name, lo, hi, p, n)
        return 1
    }
    return 0
}
FILENAME == ARGV[1] { n_all++; NAME[n_all] = $0; next }
FILENAME == ARGV[2] { next }
# The self-test of this gate holds the fixture names: they exist only inside the
# sandbox repo that test builds, so this scan reads nothing from it.
FILENAME == "tests/check_line_citations_test.sh" { next }
{
    line = $0
    residual = $0
    last = ""
    while (match(line, /[A-Za-z0-9_.\/-]+\.(py|cpp|hpp|js|mjs|go|sh|json|md|txt|cin|nsi|ts|html|htm):[0-9]+(-[0-9]+)?/)) {
        m = substr(line, RSTART, RLENGTH)
        line = substr(line, RSTART + RLENGTH)
        sep = index(m, ":")
        name = substr(m, 1, sep - 1)
        rng = substr(m, sep + 1)
        n = split(rng, b, "-")
        lo = b[1]
        hi = (n > 1 ? b[2] : b[1])
        last = name
        if (check(name, lo, hi)) bad = 1
        # the named range leaves the residual, so the bare pass cannot re-count it
        p = index(residual, m)
        if (p > 0) residual = substr(residual, 1, p - 1) " " substr(residual, p + length(m))
    }
    # A bare :N belongs to the file named earlier on the same line.
    if (last != "") {
        while (match(residual, /[^:.0-9]:[0-9]+(-[0-9]+)?/)) {
            m = substr(residual, RSTART, RLENGTH)
            residual = substr(residual, RSTART + RLENGTH)
            sub(/^[^:]:/, "", m)
            n = split(m, b, "-")
            lo = b[1]
            hi = (n > 1 ? b[2] : b[1])
            if (check(last, lo, hi)) bad = 1
        }
    }
}
END {
    if (checked == 0) {
        print "SKIP  line citations (no citation found in any tracked file)"
        exit 125
    }
    printf("checked %d citation(s)\n", checked)
    exit (bad ? 1 : 0)
}
' "$all_list" "$scan_list" "${files[@]}"

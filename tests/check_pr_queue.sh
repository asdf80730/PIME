#!/usr/bin/env bash
# The open-PR queue read by hand is a table of 21 sequential `gh` calls whose
# GraphQL fields truncate, which is how a signing FAIL and a `mergeable` that
# never settled both slipped past a snapshot. This is the same extract in one
# deterministic pass: one row per open PR with its head SHA, its mergeability,
# and the conclusions of every check that reported.
#
# A first-pass `UNKNOWN` is not a disposition — GitHub computes the field
# asynchronously — so each such PR is re-read once and only the second value is
# recorded. The row set is complete or the gate is red: a head SHA missing from
# a row, or an `UNKNOWN` surviving the re-read, is an unfinished snapshot.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later
#
# Usage: check_pr_queue.sh [<owner/repo>]
# Exit codes: 0 the snapshot is complete, 1 a row is unfinished,
# 125 not applicable (no checkout, no `gh`, or the repo answers nothing).

set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  PR queue (not inside a git checkout)\n'
    exit 125
}
cd "$ROOT" || exit 1

REPO=${1:-EasyIME/PIME}
# `GH_BIN` lets the self-test point at a stub; a box without the CLI still
# answers 125 rather than a red.
gh_bin=${GH_BIN:-gh}
command -v "$gh_bin" >/dev/null 2>&1 || {
    printf 'SKIP  PR queue (no gh on PATH)\n'
    exit 125
}

# The `join("|")` form is what the built-in jq parser here accepts for a mixed
# row: an interpolated string with a nested `//` chain dies on its own parser,
# and a tab-separated row collapses its empty fields under `read`.
rows=$("$gh_bin" pr list --repo "$REPO" --state open \
    --json number,headRefOid,mergeable,statusCheckRollup \
    --jq '.[] | [(.number|tostring), .headRefOid, .mergeable, ([.statusCheckRollup[]? | .conclusion // .state // "?"] | join(","))] | join("|")' \
    2>/dev/null)
[ -n "$rows" ] || {
    printf 'SKIP  PR queue (%s answers no open pull requests)\n' "$REPO"
    exit 125
}

bad=0
seen=0
while IFS='|' read -r number sha mergeable checks; do
    [ -n "$number" ] || continue
    seen=$((seen + 1))
    if [ -z "$sha" ] || [ "$sha" = "null" ]; then
        printf 'FAIL  PR queue: #%s carries no head SHA\n' "$number"
        bad=1
        continue
    fi
    if [ "$mergeable" = "UNKNOWN" ]; then
        mergeable=$(gh pr view "$number" --repo "$REPO" --json mergeable \
            --jq .mergeable 2>/dev/null)
        [ -n "$mergeable" ] || mergeable=UNKNOWN
    fi
    if [ "$mergeable" = "UNKNOWN" ]; then
        printf 'FAIL  PR queue: #%s still reads mergeable=UNKNOWN after the re-read\n' "$number"
        bad=1
    fi
    printf '#%s %s mergeable=%s checks=%s\n' \
        "$number" "${sha:0:8}" "$mergeable" "${checks:-none}"
done <<< "$rows"

if [ "$bad" -ne 0 ]; then
    printf 'FAIL  PR queue (%s row(s) read)\n' "$seen"
    exit 1
fi
printf 'PASS  PR queue (%s open PR(s) on %s)\n' "$seen" "$REPO"
exit 0

#!/usr/bin/env bash
# The open-PR queue read by hand is a table of 21 sequential `gh` calls whose
# GraphQL fields truncate, which is how a signing FAIL and a `mergeable` that
# never settled both slipped past a snapshot. This is the same extract in one
# deterministic pass: one row per open PR with its head SHA, its mergeability,
# and the conclusions of every check that reported.
#
# A first-pass `UNKNOWN` is not a disposition — GitHub computes the field
# asynchronously — so each such PR is re-read once and only the second value is
# recorded. The row set is complete or the gate is red: a head SHA missing from
# a row, an `UNKNOWN` surviving the re-read, one head carried by two open PRs,
# or a row whose head is not the tip of its own local branch.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later
#
# Usage: check_pr_queue.sh [<owner/repo>]
# Exit codes: 0 the snapshot is complete, 1 a row is unfinished,
# 125 not applicable (no checkout, no `gh`, or the repo answers nothing).

set -u

. "${BASH_SOURCE[0]%/*}/gate_lib.sh"

gate_root 'PR queue' || exit $?

REPO=${1:-EasyIME/PIME}
# `GH_BIN` lets the self-test point at a stub; a box without the CLI still
# answers 125 rather than a red.
gh_bin=${GH_BIN:-gh}
command -v "$gh_bin" >/dev/null 2>&1 || {
    printf 'SKIP  PR queue (no gh on PATH)\n'
    exit 125
}

# The `join("|")` form is what the built-in jq parser here accepts for a mixed
# row: an interpolated string with a nested `//` chain dies on its own parser,
# and a tab-separated row collapses its empty fields under `read`.
rest=0
rows=$("$gh_bin" pr list --repo "$REPO" --state open \
    --json number,headRefOid,mergeable,statusCheckRollup,headRefName \
    --jq '.[] | [(.number|tostring), .headRefOid, .mergeable, ([.statusCheckRollup[]? | .conclusion // .state // "?"] | join(",")), .headRefName] | join("|")' \
    2>/dev/null)
if [ -z "$rows" ]; then
    # `gh pr list` and `gh pr view` answer through GraphQL, which a tokenless gh
    # cannot use (`HTTP 401: Requires authentication`); the REST endpoints answer
    # without a token. Take the same five fields from them rather than letting a
    # missing token read as "the repo has no open PRs". `mergeable` is a bare
    # JSON null there, so it is spelled UNKNOWN to match the enum's unsettled
    # value; the rollup has no REST twin, so each head's checks come from the
    # check-runs endpoint.
    rest=1
    base=$("$gh_bin" api "repos/$REPO/pulls?state=open&per_page=100" \
        --jq '.[] | [(.number|tostring), .head.sha, (if .mergeable == null then "UNKNOWN" else (.mergeable|tostring) end), .head.ref] | join("|")' \
        2>/dev/null)
    # A tokenless box gets 60 REST calls per hour per IP, and one exhausted
    # window answers the limit body instead of the array. That is not a red row:
    # the snapshot is simply unavailable, so it reads as 125 like a missing gh.
    case "$base" in
        '{"message":"API rate limit'*)
            printf 'SKIP  PR queue (REST limit reached: %s)\n' "$base"
            exit 125 ;;
    esac
    rows=""
    while IFS='|' read -r number sha mergeable branch; do
        [ -n "$number" ] || continue
        checks=$("$gh_bin" api "repos/$REPO/commits/$sha/check-runs" \
            --jq '[.check_runs[]? | .conclusion // .status // "?"] | join(",")' 2>/dev/null)
        case "$checks" in
            '{"message":"API rate limit'*)
                printf 'SKIP  PR queue (REST limit reached on #%s: %s)\n' "$number" "$checks"
                exit 125 ;;
        esac
        rows+="${number}|${sha}|${mergeable}|${checks:-none}|${branch}"$'\n'
    done <<< "$base"
    rows=${rows%$'\n'}
fi
[ -n "$rows" ] || {
    printf 'SKIP  PR queue (%s answers no open pull requests)\n' "$REPO"
    exit 125
}

bad=0
seen=0
head_nums=()
head_shas=()
while IFS='|' read -r number sha mergeable checks branch; do
    [ -n "$number" ] || continue
    seen=$((seen + 1))
    if [ -z "$sha" ] || [ "$sha" = "null" ]; then
        printf 'FAIL  PR queue: #%s carries no head SHA\n' "$number"
        bad=1
        continue
    fi
    if [ "$mergeable" = "UNKNOWN" ]; then
        if [ "$rest" = 1 ]; then
            re=$( "$gh_bin" api "repos/$REPO/pulls/$number" --jq \
                'if .mergeable == null then "UNKNOWN" else (.mergeable|tostring) end' 2>/dev/null)
        else
            re=$("$gh_bin" pr view "$number" --repo "$REPO" --json mergeable \
                --jq .mergeable 2>/dev/null)
        fi
        [ -n "$re" ] || re=UNKNOWN
        mergeable=$re
    fi
    if [ "$mergeable" = "UNKNOWN" ]; then
        printf 'FAIL  PR queue: #%s still reads mergeable=UNKNOWN after the re-read\n' "$number"
        bad=1
    fi
    # Two reads the hand-built table kept missing, both free once the row set is
    # in one pass. A head shared by two open PRs is the #1014 shape: one
    # force-push invalidates the other PR's evidence, and the maintainer's
    # `ready to merge` lands on whichever head was read last. A local branch
    # whose tip is not the head GitHub reports means the posted CI evidence
    # belongs to a tree the ref no longer is.
    for i in "${!head_shas[@]}"; do
        if [ "${head_shas[$i]}" = "$sha" ]; then
            printf 'FAIL  PR queue: #%s and #%s share head %s; one head per PR\n' \
                "$number" "${head_nums[$i]}" "${sha:0:8}"
            bad=1
        fi
    done
    head_nums+=("$number")
    head_shas+=("$sha")
    if [ -n "$branch" ] &&
            local_sha=$(git rev-parse --verify --quiet "$branch^{commit}") &&
            [ "$local_sha" != "$sha" ]; then
        printf 'FAIL  PR queue: #%s head is %s but %s is %s; push or re-post\n' \
            "$number" "${sha:0:8}" "$branch" "${local_sha:0:8}"
        bad=1
    fi
    printf '#%s %s mergeable=%s checks=%s\n' \
        "$number" "${sha:0:8}" "$mergeable" "${checks:-none}"
done <<< "$rows"

if [ "$bad" -ne 0 ]; then
    printf 'FAIL  PR queue (%s row(s) read)\n' "$seen"
    exit 1
fi
printf 'PASS  PR queue (%s open PR(s) on %s)\n' "$seen" "$REPO"
exit 0

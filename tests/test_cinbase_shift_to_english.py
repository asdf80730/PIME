import unittest
from unittest.mock import MagicMock

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), os.path.pardir))
PYTHON_DIR = os.path.join(ROOT, "python")
TESTS_DIR = os.path.dirname(os.path.abspath(__file__))
for path in (PYTHON_DIR, TESTS_DIR):
    if path not in sys.path:
        sys.path.insert(0, path)

import ime_smoke_runner  # noqa: E402 - located after ROOT is known
ime_smoke_runner.install_windows_shims()

from cinbase import CHINESE_MODE, ENGLISH_MODE  # noqa: E402

VK_SHIFT = 0x10


class CinbaseKeyHarness(unittest.TestCase):
    """Drives the real chesimplex service through the client's key seam."""

    def setUp(self):
        self.old_appdata = os.environ.get("APPDATA")
        self.old_cwd = os.getcwd()
        self.temp_dir = tempfile.TemporaryDirectory(prefix="pime-shift-eng-")
        os.environ["APPDATA"] = self.temp_dir.name
        os.chdir(self.temp_dir.name)

    def tearDown(self):
        os.chdir(self.old_cwd)
        if self.old_appdata is None:
            os.environ.pop("APPDATA", None)
        else:
            os.environ["APPDATA"] = self.old_appdata
        self.temp_dir.cleanup()

    @staticmethod
    def key_event(char_code, key_code=None, printable=False, shift=False):
        event = MagicMock()
        event.charCode = char_code
        event.keyCode = char_code if key_code is None else key_code
        event.seqNum = 1
        event.repeatCount = 1
        event.scanCode = 0
        event.isExtended = False
        event.keyStates = [0] * 256
        event.isPrintableChar.return_value = printable
        event.isKeyDown.side_effect = lambda vk: vk == VK_SHIFT and shift
        event.isKeyToggled.return_value = False
        return event

    def send(self, service, char_code, key_code=None, printable=False, shift=False):
        """Dispatch one keydown and return the commitString it produced."""
        event = self.key_event(char_code, key_code, printable, shift)
        service.currentReply = {}
        if service.filterKeyDown(event):
            service.onKeyDown(event)
        return service.currentReply.get("commitString", "")

    def activate_chepinyin_roman(self):
        """The 拼音 service on its 通用拼音 table, the one shipped cinbase
        table whose keyname map holds no ``w``/``y``: exactly those letters
        reach the not-isInKeyName half of the key dispatch."""
        from input_methods.chepinyin import chepinyin_ime

        service = chepinyin_ime.ChePinyinTextService(ime_smoke_runner.FakeClient())
        service.onActivate()
        for _ in range(500):
            if chepinyin_ime.CinTable.cin is not None and not chepinyin_ime.CinTable.loading:
                break
            time.sleep(0.02)
        service.cfg.selCinType = 2
        service.reLoadCinTable = True
        loader = chepinyin_ime.LoadCinTable(service, chepinyin_ime.CinTable)
        future = loader.start()
        if future is None:  # the pre-#1004 loader is a threading.Thread
            loader.join(30)
        else:
            future.result(30)
        service.cin = chepinyin_ime.CinTable.cin
        self.assertFalse(service.cin.isInKeyName("w"),
                         "setup: w sits outside the roman keyname map")
        return service

    def activate_chesimplex(self):
        from input_methods.chesimplex import chesimplex_ime

        service = chesimplex_ime.CheSimplexTextService(ime_smoke_runner.FakeClient())
        service.onActivate()
        for _ in range(500):
            if chesimplex_ime.CinTable.cin is not None and not chesimplex_ime.CinTable.loading:
                break
            time.sleep(0.02)
        self.assertIsNotNone(chesimplex_ime.CinTable.cin)
        return service

    def commit_char(self, service, char):
        """Type a table key for char, then confirm char via space or sel key."""
        self.assertTrue(service.cin.isHaveKey(char), f"setup: {char!r} in 速成 table")
        key = service.cin.getKey(char)
        for ch in key:
            self.send(service, ord(ch), ord(ch), printable=True)
        cands = list(service.candidateList)
        self.assertIn(char, cands, f"setup: {char!r} offered for key {key!r}")
        if len(cands) == 1:
            out = self.send(service, 0x20, 0x20)
        else:
            out = self.send(service, ord(str(cands.index(char) + 1)), printable=True)
        self.assertEqual(out, char, f"setup: committing {char!r} via {key!r}")
        return key


class CinbaseShiftToEnglishTests(CinbaseKeyHarness):
    def test_shift_letter_switches_to_english_when_enabled(self):
        service = self.activate_chesimplex()
        service.shiftLetterSwitchToEnglish = True

        commit = self.send(service, ord("H"), ord("H"), printable=True, shift=True)

        self.assertEqual(commit, "H")
        self.assertEqual(service.langMode, ENGLISH_MODE)

    def test_shift_letter_keeps_chinese_mode_when_disabled(self):
        service = self.activate_chesimplex()
        service.shiftLetterSwitchToEnglish = False

        commit = self.send(service, ord("H"), ord("H"), printable=True, shift=True)

        self.assertEqual(commit, "H")
        self.assertEqual(service.langMode, CHINESE_MODE)

    def test_shift_letter_from_phrase_window_switches_to_english(self):
        service = self.activate_chesimplex()
        service.showPhrase = True
        service.shiftLetterSwitchToEnglish = True
        self.commit_char(service, "中")
        self.assertTrue(service.phrasemode, "setup: phrase window is open")

        commit = self.send(service, ord("H"), ord("H"), printable=True, shift=True)

        self.assertEqual(commit, "H")
        self.assertEqual(service.langMode, ENGLISH_MODE)
        self.assertFalse(service.phrasemode)
        self.assertFalse(service.isShowPhraseCandidates)

    def test_shift_letter_during_composition_does_not_switch(self):
        service = self.activate_chesimplex()
        service.shiftLetterSwitchToEnglish = True
        self.send(service, ord("b"), ord("b"), printable=True)
        self.assertTrue(service.isComposing())

        self.send(service, ord("a"), ord("a"), printable=True)
        self.send(service, ord("H"), ord("H"), printable=True, shift=True)

        self.assertEqual(service.langMode, CHINESE_MODE)

    def test_shift_letter_beats_easy_symbols_when_enabled(self):
        service = self.activate_chesimplex()
        service.shiftLetterSwitchToEnglish = True
        service.easySymbolsWithShift = True

        commit = self.send(service, ord("H"), ord("H"), printable=True, shift=True)

        self.assertEqual(service.langMode, ENGLISH_MODE)
        self.assertEqual(commit, "H")

    def test_small_letter_policy_applies_on_switch(self):
        # onActivate reads the real GetKeyState(VK_CAPITAL) into capsStates
        # (cinbase/__init__.py onActivate), so pin CapsLock off before
        # activation, not only before the keystroke.
        import cinbase

        original = cinbase.CinBase.getKeyState
        cinbase.CinBase.getKeyState = lambda *args: False
        try:
            service = self.activate_chesimplex()
            service.shiftLetterSwitchToEnglish = True
            service.outputSmallLetterWithShift = True
            commit = self.send(service, ord("H"), ord("H"), printable=True, shift=True)
        finally:
            cinbase.CinBase.getKeyState = original

        self.assertEqual(commit, "h")
        self.assertEqual(service.langMode, ENGLISH_MODE)


    def test_shift_letter_outside_the_keyname_map_switches(self):
        # The not-isInKeyName half of onKeyDown: on the roman table w is not a
        # radical, so without the second branch the mode stays Chinese.
        service = self.activate_chepinyin_roman()
        service.shiftLetterSwitchToEnglish = True

        commit = self.send(service, ord("W"), ord("W"), printable=True, shift=True)

        self.assertEqual(commit, "W")
        self.assertEqual(service.langMode, ENGLISH_MODE)

    def test_shift_letter_outside_keyname_map_commits_with_full_shape(self):
        # Same letter with Shift full-shape punctuation on: the fall-through
        # answered nothing at all, so the keypress was swallowed.
        service = self.activate_chepinyin_roman()
        service.shiftLetterSwitchToEnglish = True
        service.fullShapeSymbols = True

        commit = self.send(service, ord("W"), ord("W"), printable=True, shift=True)

        self.assertEqual(commit, "W")
        self.assertEqual(service.langMode, ENGLISH_MODE)



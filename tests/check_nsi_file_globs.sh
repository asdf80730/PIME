#!/usr/bin/env bash
# Ticket: `.scratch/two-axis-review-2026-11-16/issues/05-name-the-two-orphan-test-files.md`
# — this gate catches a `File` directive of `installer/installer.nsi` reaching
# no path, where the values after `/x` and an `/oname=` word are not paths,
# `*.*` means every entry of the directory, and a `.gitignore`d path is
# `build.bat` output.
#
# Every `File` directive of `installer/installer.nsi` names at least one path.
#
# makensis aborts on a `File` line whose glob matches nothing (`no files found`,
# exit 1), and it is the last step of the `build-and-sign` job, so the miss
# surfaces eight minutes after the push. The Linux NSIS step cannot see it
# either: `tests/run_local_tests.sh` rewrites every directive to `File /nonfatal`
# so a tree without build output still assembles, which also silences the
# zero-match class. Measured 2026-11-13 on PR #1021: the rime engine folder moved
# to `python/rimebase` while the `brise` submodule stayed at
# `python/input_methods/rime/brise` (`.gitmodules`), and the five `File` lines
# followed the folder name instead of the submodule path.
#
# What counts as answered, per directive, in NSIS' own order:
#   - options (`/r`, `/nonfatal`, `/a`, `/N`, `/local`) and the value after `/x`
#     or an `/oname=` word are not paths;
#   - a relative path resolves against the script's own directory, so `..\x`
#     is the checkout-root-relative `x`;
#   - `*.*` means every entry of the directory, as NSIS expands it;
#   - a path `.gitignore` excludes is build output (`build`, `build64`,
#     `build_arm64`, the webpack `dist`s) and is answered by `build.bat`, so it
#     is skipped here rather than demanded before `build.bat` has run.
#
# Usage: check_nsi_file_globs.sh   (run from any checkout)
# Exit codes: 0 every directive resolves, 1 a directive matched nothing,
# 125 not applicable (not inside a git checkout, or no installer script).
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later

set -u

. "${BASH_SOURCE[0]%/*}/gate_lib.sh"

gate_root 'nsi File globs' || exit $?

NSI="installer/installer.nsi"
if [ ! -f "$NSI" ]; then
    printf 'SKIP  nsi File globs (%s missing)\n' "$NSI"
    exit 125
fi

checked=0
misses=0
lineno=0
miss_report=''
# Parallel arrays: one pass parses the script, then the globs are counted. The
# two passes keep the parse independent of the ignore decision, so a submodule
# pathspec cannot truncate the answer set.
paths=()
specs=()
lines=()

# glob_count PATH — number of entries a directive reaches; 0 is the red case.
glob_count() {
    local p=$1 g
    if [ "${p##*/}" = '*.*' ]; then
        g="${p%*.*}*"
    else
        g=$p
    fi
    compgen -G "$g" | wc -l | tr -d '[:space:]'
}

while IFS= read -r raw || [ -n "$raw" ]; do
    lineno=$((lineno + 1))
    raw=${raw%$'\r'}                     # installer.nsi is CRLF
    t=${raw#"${raw%%[![:space:]]*}"}    # drop the leading indent
    t=${t%%[[:space:]]*}                  # keep the first word for the test
    [ "$t" = "File" ] || continue

    # Re-read the line into words; quotes only group, no path here holds a space.
    # `IFS=` from the loop above would leave the whole line in one field.
    words_ifs=$IFS
    IFS=$' \t\n'
    read -r -a toks <<< "${raw#"${raw%%[![:space:]]*}"}"
    IFS=$words_ifs
    i=0
    n=${#toks[@]}
    while [ "$i" -lt "$n" ]; do
        tok=${toks[$i]}
        i=$((i + 1))
        tok=${tok#\"}; tok=${tok%\"}
        case "$tok" in
            File) continue ;;
            /x) i=$((i + 1)); continue ;;          # /x <pattern>
            /*) continue ;;                          # /r /nonfatal /a /N /local /oname=
        esac

        p=${tok//\\//}
        case "$p" in
            ../*) p=${p#../} ;;
            *) p="installer/$p" ;;
        esac
        paths+=("$p"); specs+=("$tok"); lines+=("$lineno")
    done
done < "$NSI"

# Each path asks on its own: `git check-ignore --stdin` aborts on the first
# pathspec a submodule owns (`fatal: Pathspec ... is in submodule`) and the rest
# of the batch goes unanswered, which would read as "not ignored".
for ((k = 0; k < ${#paths[@]}; k++)); do
    p=${paths[$k]}
    git check-ignore -q "$p" 2>/dev/null && continue
    checked=$((checked + 1))
    if [ "$(glob_count "$p")" = "0" ]; then
        misses=$((misses + 1))
        miss_report="${miss_report}  ${NSI}:${lines[$k]}: no files found for ${specs[$k]}"$'\n'
    fi
done

if [ "$misses" -ne 0 ]; then
    printf 'FAIL  nsi File globs (%d of %d directive path(s) matched nothing)\n' \
        "$misses" "$checked"
    printf '%s' "$miss_report"
    printf '      a zero-match File line aborts makensis; compare each name with\n'
    printf '      the .gitmodules path for a submodule.\n'
    exit 1
fi

printf 'OK    nsi File globs resolve (%d path(s) checked)\n' "$checked"

#!/usr/bin/env bash
# The census in docs/research/quotes numbers, so every quoted count has to equal
# what the joined data reads out — the same two passes
# docs/research/upstream-bug-backlog-2026-10.md §8 names. The 2026-11-12
# libchewing sweep moved two records out of `upstream-lib` into `close-out`, and
# §2 plus §8 were edited by hand, so the partition is the one place a green run
# can hide an off-by-N.
#
# Four comparisons, all against .scratch/upstream-bugs/joined.json:
#   - the §2 status table rows (`| <status> | <n> |`)
#   - the §2 `act` line (`close-out 95, needs-windows 102, ...`)
#   - the §8 partition sentence: each act's number and the `a+b+... = N` sum
#   - the §4.5 stale set: the issue numbers the section names, and the
#     comment-id table under them, against the `stale-unreproducible` records
#
# The §4.5 comparison is the one the retest sweep (ticket 51) needs: its
# acceptance is "the 25 numbers", and the section states them inside prose, so
# nothing but a join against the joined data can catch a list that no longer
# matches the bucket it claims. A census without a §4.5 section skips it.
#
# `.scratch/` is git-excluded, so a fresh clone without the joined data skips;
# the census is tracked, so its absence is a failure.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later
#
# Usage: check_census_partition.sh [<census.md> <joined.json>]
# Exit codes: 0 every quoted number reproduces, 1 a number drifted,
# 125 not applicable (no git checkout, or no joined data next to it).

set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  census partition (not inside a git checkout)\n'
    exit 125
}
cd "$ROOT" || exit 1

census=${1:-docs/research/upstream-bug-backlog-2026-10.md}
joined=${2:-.scratch/upstream-bugs/joined.json}

if [ ! -f "$joined" ]; then
    printf 'SKIP  census partition (no %s in this checkout)\n' "$joined"
    exit 125
fi
if [ ! -f "$census" ]; then
    printf 'FAIL  census partition (%s absent)\n' "$census"
    exit 1
fi

# Real counts off the joined data. The record keys sit at the four-space indent,
# so the array items under `l` never join the tally.
real_act() {
    awk -v want="$1" 'BEGIN { c = 0 }
        /^    "act": / { line = $0; sub(/^    "act": /, "", line); gsub(/[",]/, "", line); if (line == want) c++ }
        END { print c }' "$joined"
}
real_status() {
    awk -v want="$1" 'BEGIN { c = 0 }
        /^    "status": / { line = $0; sub(/^    "status": /, "", line); gsub(/[",]/, "", line); if (line == want) c++ }
        END { print c }' "$joined"
}
real_records=$(awk '/^    "n": / { c++ } END { print c + 0 }' "$joined")

# The stale bucket's issue numbers, one per line, ascending. The record's "n"
# key precedes its "status" key, so the number is remembered until the status
# line decides whether the record belongs to the bucket.
real_stale() {
    awk 'BEGIN { n = "" }
        /^    "n": / { line = $0; sub(/^    "n": /, "", line); gsub(/[^0-9]/, "", line); n = line }
        /^    "status": / { line = $0; sub(/^    "status": /, "", line); gsub(/[", \r]/, "", line); if (line == "stale-unreproducible") print n }
    ' "$joined" | sort
}

fail=0

# Quoted numbers off the census, one state machine over the two sections.
quoted=$(awk '
    BEGIN { FS = "|" }
    /^## / { section = $0 }
    section ~ /^## 2\./ && /^\| status \| n \|/ { in_status = 1; next }
    in_status && /^\|/ { name = $2; count = $3; gsub(/ /, "", name); gsub(/ /, "", count); if (name != "---" && name != "status") print "status " name " " count; next }
    in_status && !/^\|/ { in_status = 0 }
    /^.act. \(what should happen\)/ { in_act = 1 }
    in_act {
        line = $0
        gsub(/\*/, "", line)
        n = split(line, parts, ",")
        for (i = 1; i <= n; i++) {
            if (match(parts[i], /[a-z-]+ [0-9]+/)) {
                pair = substr(parts[i], RSTART, RLENGTH)
                split(pair, kv, " ")
                print "act " kv[1] " " kv[2]
            }
        }
    }
    in_act && /^$/ { in_act = 0 }
    /^ *- Partition of the/ { in_part = 1 }
    in_part {
        line = $0
        gsub(/\*/, "", line)
        m = split(line, parts, ",")
        for (i = 1; i <= m; i++) {
            if (match(parts[i], /(close-out|needs-windows|upstream-lib|fixable-here|dead)[ ]+[0-9]+/)) {
                pair = substr(parts[i], RSTART, RLENGTH)
                n2 = split(pair, kv, " ")
                if (!(kv[1] in seen)) { seen[kv[1]] = 1; print "part " kv[1] " " kv[2] }
            }
        }
        if (match(line, /[0-9]+(\+[0-9]+)* = [0-9]+/)) {
            expr = substr(line, RSTART, RLENGTH)
            split(expr, halves, "=")
            gsub(/ /, "", halves[1])
            gsub(/[^0-9]/, "", halves[2])
            print "sum " halves[1] " " halves[2]
            in_part = 0
        }
    }
' "$census")

# 1. The §2 status table.
while IFS=' ' read -r kind name count; do
    [ "$kind" = "status" ] || continue
    want=$(real_status "$name")
    if [ "$want" != "$count" ]; then
        printf 'FAIL  census partition: status %s quoted as %s, joined data has %s\n' "$name" "$count" "$want"
        fail=1
    fi
done <<< "$quoted"

# 2+3. The act line, the §8 per-act numbers, and the sum.
for kind in act part; do
    while IFS=' ' read -r k name count; do
        [ "$k" = "$kind" ] || continue
        want=$(real_act "$name")
        if [ "$want" != "$count" ]; then
            printf 'FAIL  census partition: %s count for act %s quoted as %s, joined data has %s\n' "$kind" "$name" "$count" "$want"
            fail=1
        fi
    done <<< "$quoted"
done
for name in close-out needs-windows upstream-lib fixable-here dead; do
    printf '%s\n' "$quoted" | grep -q "^act $name " || {
        printf 'FAIL  census partition: act %s never quoted on the act line\n' "$name"
        fail=1
    }
    printf '%s\n' "$quoted" | grep -q "^part $name " || {
        printf 'FAIL  census partition: act %s never quoted in the partition sentence\n' "$name"
        fail=1
    }
done
sum_line=$(printf '%s\n' "$quoted" | awk '$1=="sum" {print $2 " " $3; exit}')
if [ -z "$sum_line" ]; then
    printf 'FAIL  census partition: no `a+b+... = N` sum in the partition sentence\n'
    fail=1
else
    addends=${sum_line% *}
    total=${sum_line##* }
    computed=$(printf '%s\n' "$addends" | tr '+' '\n' | awk '{ s += $1 } END { print s + 0 }')
    if [ "$total" != "$real_records" ]; then
        printf 'FAIL  census partition: sum line totals %s, joined data holds %s records\n' "$total" "$real_records"
        fail=1
    fi
    if [ "$computed" != "$total" ]; then
        printf 'FAIL  census partition: addends %s add to %s, not %s\n' "$addends" "$computed" "$total"
        fail=1
    fi
fi

# 4. The §4.5 stale set: the issue numbers the section names, and the
# comment-id table under them, against the joined data's stale records. A
# census without a §4.5 section skips this comparison.
section45=$(awk '
    /^### 4\.5 / { in45 = 1 }
    in45 && /^### / && !/^### 4\.5 / { in45 = 0 }
    in45 { print }
' "$census")
if [ -n "$section45" ]; then
    stale_real=$(real_stale)
    stale_real_count=$(printf '%s\n' "$stale_real" | grep -c '[0-9]')
    stale_quoted=$(printf '%s\n' "$section45" | grep -o '#[0-9][0-9]*' | tr -d '#' | sort -u)
    stale_quoted_count=$(printf '%s\n' "$stale_quoted" | grep -c '[0-9]')
    if [ "$stale_quoted_count" != "$stale_real_count" ]; then
        printf 'FAIL  census partition: §4.5 names %s stale issue(s), joined data holds %s stale-unreproducible record(s)\n' \
            "$stale_quoted_count" "$stale_real_count"
        fail=1
    fi
    if [ "$stale_quoted" != "$stale_real" ]; then
        printf 'FAIL  census partition: §4.5 stale set differs from the joined data\n'
        printf '  only in §4.5: %s\n' "$(comm -23 <(printf '%s\n' "$stale_quoted") <(printf '%s\n' "$stale_real") | tr '\n' ' ')"
        printf '  only in joined data: %s\n' "$(comm -13 <(printf '%s\n' "$stale_quoted") <(printf '%s\n' "$stale_real") | tr '\n' ' ')"
        fail=1
    fi
    # The comment-id table under the section: one id per named issue, ids distinct.
    table_pairs=$(printf '%s\n' "$section45" | awk -F'|' '
        /^\| *[0-9]+ *\|/ {
            for (i = 2; i < NF; i += 2) {
                issue = $i; id = $(i + 1)
                gsub(/[ \t]/, "", issue); gsub(/[ \t]/, "", id)
                if (issue ~ /^[0-9]+$/ && id ~ /^[0-9]+$/) print issue " " id
            }
        }')
    table_count=$(printf '%s\n' "$table_pairs" | grep -c '[0-9]')
    table_issues=$(printf '%s\n' "$table_pairs" | cut -d' ' -f1 | sort)
    table_ids=$(printf '%s\n' "$table_pairs" | cut -d' ' -f2 | sort)
    if [ "$table_count" != "$stale_quoted_count" ]; then
        printf 'FAIL  census partition: §4.5 comment-id table holds %s row(s), the section names %s issue(s)\n' \
            "$table_count" "$stale_quoted_count"
        fail=1
    fi
    if [ "$(printf '%s\n' "$table_issues" | sort -u | grep -c '[0-9]')" != "$table_count" ]; then
        printf 'FAIL  census partition: §4.5 comment-id table names an issue twice\n'
        fail=1
    fi
    if [ "$(printf '%s\n' "$table_ids" | uniq -d | grep -c '[0-9]')" != "0" ]; then
        printf 'FAIL  census partition: §4.5 comment-id table repeats a comment id\n'
        fail=1
    fi
    if [ "$table_issues" != "$stale_quoted" ]; then
        printf 'FAIL  census partition: §4.5 comment-id table does not cover the named issues\n'
        fail=1
    fi
fi

if [ "$fail" -eq 0 ]; then
    printf 'PASS  census partition (%s records; act and status tallies match the joined data)\n' "$real_records"
    exit 0
fi
printf 'Re-derive with: jq -r ".[] | \"\\(.act)|\\(.status)\"" %s | sort | uniq -c\n' "$joined"
exit 1

#!/usr/bin/env bash
# The two `gh`-backed gates answer from a stub their self-test writes with
# `cat >`, which leaves the file 644. A non-executable file is invisible to
# `command -v`, so the gate silently falls back to whatever real `gh` the box
# carries: on the Linux runner that one holds no token, answers empty, and the
# gate reports its 125 skip for every case — a red layer whose cause is the
# stub's mode bits. Both halves of the wiring are therefore contract: the stub
# is chmod-ed, and the gate call names it through its own GH_BIN knob rather
# than trusting PATH order.
#
# Rule per `tests/*_test.sh` that writes a `gh` stub:
#   - it chmods the stub (`755` or `+x`), and
#   - at least one gate call in the file sets GH_BIN to that stub.
# A self-test with no stub heredoc is not this gate's business.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later
#
# Usage: check_gh_stubs.sh [<tests-dir>]
#   <tests-dir>  directory holding the self-tests, default `tests`
# Exit codes: 0 every stub is wired, 1 one is not,
# 125 not applicable (no checkout, no tests dir, no stub self-test).

set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  gh stub wiring (not inside a git checkout)\n'
    exit 125
}
cd "$ROOT" || exit 1

tests=${1:-tests}
[ -d "$tests" ] || {
    printf 'SKIP  gh stub wiring (%s absent)\n' "$tests"
    exit 125
}

shopt -s nullglob

bad=0
seen=0
for f in "$tests"/*_test.sh; do
    grep -q 'cat >"$SANDBOX/gh" <<' "$f" || continue
    seen=$((seen + 1))
    if ! grep -qE 'chmod (755|\+x) "\$SANDBOX/gh"' "$f"; then
        printf 'the stub in %s is never chmod-ed, so command -v ignores it\n' "$f"
        bad=1
    fi
    if ! grep -q 'GH_BIN="$SANDBOX/gh"' "$f"; then
        printf 'no gate call in %s names the stub through GH_BIN, so PATH order decides\n' "$f"
        bad=1
    fi
done

if [ "$seen" -eq 0 ]; then
    printf 'SKIP  gh stub wiring (%s carries no stub self-test)\n' "$tests"
    exit 125
fi

if [ "$bad" -ne 0 ]; then
    printf 'FAIL  gh stub wiring\n'
    exit 1
fi

printf 'PASS  gh stub wiring (%s stub self-test(s) chmod-ed and named through GH_BIN)\n' "$seen"
exit 0

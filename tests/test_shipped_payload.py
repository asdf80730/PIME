"""Contract checks for the two shipped facts the payload names by hand.

``version.txt`` is read three ways: ``CMakeLists.txt`` turns it into
``PIME_VERSION``, ``appveyor.artifacts.ps1`` builds the ``PIME-<version>-setup.exe``
artifact name from it, and the settings page fetches ``/version.txt`` for the About
line. The tag is what a release cut moves, so the two drift apart silently between
cuts. The libchewing data dir is the other hand-maintained set: ``chewing_new2``
looks its names up literally, so a retired or missing file changes the answers
without any import error.

Ticket 05 ``name-the-two-orphan-test-files`` (two-axis review 2026-11-16).
The five cases below are the whole pin: the ``version.txt`` shape, its match
against the latest tag, the libchewing data set, the retired trio, and the
committed ``config/config.json`` bytes. The wire reply-key set is pinned
elsewhere, by ``tests/wire-fixtures.json`` and its four adapter suites.

Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
"""

import os
import subprocess
import sys
import tempfile
import unittest

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), os.path.pardir))
for _path in (os.path.join(ROOT, "python"), os.path.dirname(os.path.abspath(__file__))):
    if _path not in sys.path:
        sys.path.insert(0, _path)

from cinbase import config  # noqa: E402

DATA_DIR = os.path.join(ROOT, "python", "libchewing", "data")
# what AssetLoader and the two DEFAULT_DICT_NAMES look for, per
# docs/agents/chewing-api.md
SHIPPED_DATA = ("word.dat", "tsi.dat", "swkb.dat", "symbols.dat")
# the 0.5.x trio, retired when the trie split into word/tsi and the pinyin table
# was compiled into the library
RETIRED_DATA = ("dictionary.dat", "index_tree.dat", "pinyin.tab")


def read(path):
    with open(path, encoding="utf-8") as handle:
        return handle.read()


class VersionContractTests(unittest.TestCase):
    def setUp(self):
        self.version = read(os.path.join(ROOT, "version.txt")).strip()

    def test_version_is_numeric_with_an_optional_suffix(self):
        # CMakeLists.txt splits on [0-9]+, so the numeric core has to be there.
        core = self.version.split("-")[0].split(".")
        self.assertGreaterEqual(len(core), 3, "version.txt has no major.minor.patch")
        for part in core:
            self.assertTrue(part.isdigit(), f"non-numeric version part {part!r}")

    def test_version_matches_the_latest_tag(self):
        try:
            proc = subprocess.run(
                ["git", "describe", "--tags", "--abbrev=0"],
                cwd=ROOT, capture_output=True, text=True, timeout=30,
            )
        except (OSError, subprocess.SubprocessError) as exc:
            self.skipTest(f"git unavailable ({exc})")
        if proc.returncode != 0:
            self.skipTest(f"no tag to compare against: {proc.stderr.strip()}")
        tag = proc.stdout.strip()
        self.assertEqual(self.version, tag[1:] if tag.startswith("v") else tag,
                         "version.txt and the newest tag disagree")


class LibchewingPayloadTests(unittest.TestCase):
    def test_shipped_data_files_are_present_and_non_empty(self):
        for name in SHIPPED_DATA:
            path = os.path.join(DATA_DIR, name)
            with self.subTest(name=name):
                self.assertTrue(os.path.isfile(path), f"{name} missing from the payload")
                self.assertGreater(os.path.getsize(path), 0, f"{name} is empty")

    def test_retired_trio_stays_out_of_the_payload(self):
        for name in RETIRED_DATA:
            with self.subTest(name=name):
                self.assertFalse(os.path.exists(os.path.join(DATA_DIR, name)),
                                 f"{name} is the retired 0.5.x spelling")


class ShippedConfigTests(unittest.TestCase):
    def test_committed_configs_are_the_writer_bytes(self):
        # INV-02: CONFIG_RECORDS is the one declaration, so every shipped
        # config.json is a projection of it and a re-run is a no-op.
        with tempfile.TemporaryDirectory() as tmp:
            config.write_shipped_configs(tmp)
            for ime in config.IME_DIRS:
                committed = os.path.join(ROOT, "python", "input_methods",
                                         ime, "config", "config.json")
                derived = os.path.join(tmp, "input_methods", ime, "config",
                                       "config.json")
                with self.subTest(ime=ime):
                    self.assertTrue(os.path.isfile(committed),
                                    f"{ime} ships no config.json")
                    self.assertEqual(read(committed), read(derived),
                                     f"{ime} config.json is not the writer bytes")


if __name__ == "__main__":
    unittest.main()

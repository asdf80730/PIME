def load_generator():
    """Import cnsstroke2cin.py by path; like the converter it is a tool, not a package member."""
    spec = importlib.util.spec_from_file_location("cnsstroke2cin_for_tests", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def parse_cin(text):
    """Read the CMIME blocks of a .cin text into plain data, independent of the engine."""
    heads = {}
    keynames = {}
    chardefs = {}
    state = "head"
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if state == "head":
            if line == "%keyname begin":
                state = "keyname"
            elif line == "%chardef begin":
                state = "chardef"
            elif line.startswith("%"):
                head, _, rest = line.partition(" ")
                heads[head] = rest.strip()
            continue
        if state == "keyname":
            if line == "%keyname end":
                state = "head"
                continue
            key, _, root = line.partition(" ")
            keynames[key] = root
            continue
        if state == "chardef":
            if line == "%chardef end":
                state = "head"
                continue
            key, _, root = line.partition(" ")
            chardefs.setdefault(key, []).append(root)
    return heads, keynames, chardefs


class StrokeCinFixture:
    """Hand-written CNS open-data stand-in: CNS字碼 -> 筆順, joined via CNS2UNICODE."""

    def __init__(self, strokes, mappings):
        self._strokes = strokes
        self._mappings = mappings
        self._dir = None

    def __enter__(self):
        self._dir = tempfile.mkdtemp(prefix="cns-stroke-fixture-")
        strokes_path = os.path.join(self._dir, "CNS_strokes_sequence.txt")
        with open(strokes_path, "w", encoding="utf-8", newline="\n") as handle:
            for cns_code, sequence in self._strokes:
                handle.write("%s\t%s\n" % (cns_code, sequence))
        mapping_paths = []
        for name, rows in self._mappings.items():
            path = os.path.join(self._dir, name)
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                for cns_code, codepoint in rows:
                    handle.write("%s\t%s\n" % (cns_code, codepoint))
            mapping_paths.append(path)
        self.strokes_path = strokes_path
        self.mapping_paths = mapping_paths
        self.directory = self._dir
        return self

    def __exit__(self, *exc_info):
        shutil.rmtree(self._dir, ignore_errors=True)


def generate(fixture, release="20260805"):
    return load_generator().generate_cin(
        fixture.strokes_path, fixture.mapping_paths, release=release)



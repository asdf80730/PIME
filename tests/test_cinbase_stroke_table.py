class GeneratorSeamTests(unittest.TestCase):

    def test_chardefs_use_only_the_five_stroke_keys(self):
        """CNS digit codes 1..5 become the Five-stroke keys and nothing else."""
        with StrokeCinFixture(COMMON_CNS, COMMON_MAPPINGS) as fixture:
            cin = generate(fixture)
        heads, _keynames, chardefs = parse_cin(cin)
        for key in chardefs:
            self.assertTrue(key, "empty stroke key")
            self.assertLessEqual(set(key), FIVE_STROKE_KEYS,
                                 "a stroke key left the Five-stroke alphabet: %r" % key)
        for cns_code, sequence in COMMON_CNS:
            key = "".join(DIGIT_TO_KEY[digit] for digit in sequence)
            character = UNICODE_BY_CNS[cns_code]
            self.assertIn(character, chardefs.get(key, []),
                          "%s (%s) is missing from key %r" % (character, cns_code, key))
        self.assertEqual(heads.get("%ename"), "CnsStroke")

    def test_keyname_block_renders_the_five_stroke_glyphs(self):
        """The composition string shows 一丨丿丶乙, not the latin keys."""
        with StrokeCinFixture(COMMON_CNS, COMMON_MAPPINGS) as fixture:
            cin = generate(fixture)
        _heads, keynames, _chardefs = parse_cin(cin)
        self.assertEqual(keynames, {"h": "一", "s": "丨", "p": "丿", "n": "丶", "z": "乙"})

    def test_every_prefix_of_a_common_code_is_its_own_key(self):
        """cinbase matches exactly, so prefixes are expanded offline."""
        with StrokeCinFixture(COMMON_CNS, COMMON_MAPPINGS) as fixture:
            cin = generate(fixture)
        _heads, _keynames, chardefs = parse_cin(cin)
        for cns_code, sequence in COMMON_CNS:
            character = UNICODE_BY_CNS[cns_code]
            key = "".join(DIGIT_TO_KEY[digit] for digit in sequence)
            for length in range(1, len(key) + 1):
                prefix = key[:length]
                self.assertIn(character, chardefs.get(prefix, []),
                              "%s is missing from prefix key %r of %s" %
                              (character, prefix, cns_code))

    def test_codes_longer_than_thirty_strokes_are_dropped(self):
        """maxCharLength is 30: an ultra-long code never enters the table."""
        with StrokeCinFixture(LONG_STROKES, LONG_MAPPINGS) as fixture:
            cin = generate(fixture)
        _heads, _keynames, chardefs = parse_cin(cin)
        self.assertNotIn("天", [c for chars in chardefs.values() for c in chars])
        self.assertEqual(chardefs.get("s" * 30), ["文"])
        for key in chardefs:
            self.assertLessEqual(len(key), 30, "key %r exceeds maxCharLength" % key)

    def test_ultra_rare_characters_keep_only_their_full_code(self):
        """Prefixes are pruned for the extension planes, so they stay reachable
        by their complete stroke order without fanning the table out."""
        with StrokeCinFixture(RARE_STROKES, RARE_MAPPINGS) as fixture:
            cin = generate(fixture)
        _heads, _keynames, chardefs = parse_cin(cin)
        self.assertEqual(chardefs.get("shhsh"), ["㐀"])
        for prefix in ("s", "sh", "shh", "shhs"):
            self.assertNotIn("㐀", chardefs.get(prefix, []),
                             "a rare character leaked into prefix key %r" % prefix)
        self.assertEqual(chardefs.get("h"), ["一", "二", "十", "打"])

    def test_common_plane_candidates_come_first_within_a_key(self):
        """A colliding key lists the common planes before the rare ones."""
        with StrokeCinFixture(COLLIDING_STROKES, COLLIDING_MAPPINGS) as fixture:
            cin = generate(fixture)
        _heads, _keynames, chardefs = parse_cin(cin)
        self.assertEqual(chardefs.get("hhh"), ["打", "万", "㐅"])

    def test_attribution_exhibit_ships_in_the_generated_header(self):
        """The OGDL-1.0 顯名聲明 is present, and stays a comment block."""
        with StrokeCinFixture(COMMON_CNS, COMMON_MAPPINGS) as fixture:
            cin = generate(fixture, release=RELEASE)
        header, _, _rest = cin.partition("%gen_inp")
        for line in ATTRIBUTION_EXHIBIT:
            self.assertIn(line + "\n", header, "missing 顯名聲明 line: %r" % line)
        self.assertIn("顯名聲明", header)
        self.assertIn("CNS_strokes_sequence.txt", header)
        self.assertIn("CNS2UNICODE_Unicode", header)
        for line in header.splitlines():
            self.assertTrue(not line.strip() or line.startswith("#"),
                            "header must stay a comment block, found %r" % line)

    def test_regeneration_is_byte_identical(self):
        """The same inputs reproduce the table byte for byte, in-process or by CLI."""
        with StrokeCinFixture(COMMON_CNS, COMMON_MAPPINGS) as fixture:
            first = generate(fixture, release=RELEASE)
            second = generate(fixture, release=RELEASE)
            self.assertEqual(first, second)
            outputs = []
            with tempfile.TemporaryDirectory(prefix="cns-stroke-out-") as outdir:
                for index, seed in enumerate(("0", "1", "12345")):
                    out_path = os.path.join(outdir, "stroke-%d.cin" % index)
                    env = dict(os.environ, PYTHONHASHSEED=seed)
                    subprocess.run(
                        [sys.executable, GENERATOR, fixture.strokes_path,
                         fixture.directory, "-o", out_path, "--release", RELEASE],
                        check=True, env=env,
                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
                    with open(out_path, "rb") as handle:
                        outputs.append(handle.read())
        self.assertEqual(outputs[0], outputs[1])
        self.assertEqual(outputs[1], outputs[2])
        self.assertEqual(outputs[0], first.encode("utf-8"),
                         "the CLI and the generator function disagree")

    def test_planes_past_the_pruning_line_stay_out_of_the_table(self):
        """CJK Ext-B and beyond are the ultra-rare tail the budget note prunes."""
        with StrokeCinFixture(ULTRA_RARE_STROKES, ULTRA_RARE_MAPPINGS) as fixture:
            cin = generate(fixture)
        _heads, _keynames, chardefs = parse_cin(cin)
        self.assertNotIn("𠀋", [c for chars in chardefs.values() for c in chars])
        self.assertEqual(sorted(chardefs), ["h", "hh", "hs", "hz", "hzh", "hzhh", "hzhhz"])

    def test_unjoinable_inputs_fail_loudly(self):
        """Pointing the tool at the wrong files must not yield a silent empty table."""
        with StrokeCinFixture(COMMON_CNS, {}) as fixture:
            with self.assertRaises(ValueError):
                generate(fixture)

    def test_a_tier_the_generator_does_not_know_is_an_error(self):
        """A charset tier cintojson.py adds must not silently drop characters."""
        class UnknownTierClassifier:
            def getCharSet(self, key, root):
                return "cjkExtZ"

        module = load_generator()
        original = module.load_charset_classifier
        module.load_charset_classifier = UnknownTierClassifier
        try:
            with StrokeCinFixture(COMMON_CNS, COMMON_MAPPINGS) as fixture:
                with self.assertRaises(ValueError):
                    module.generate_cin(fixture.strokes_path,
                                        fixture.mapping_paths, RELEASE)
        finally:
            module.load_charset_classifier = original


# Transcribed from CNS_strokes_sequence.txt; the committed table must say the
# same thing. 㐀 is the CJK-Ext sample.
SAMPLED_CNS_SEQUENCES = {
    "一": "1",
    "二": "11",
    "十": "12",
    "人": "34",
    "打": "15115",
    "㐀": "21121",
}

# The Big5 常用 and 次常用 planes by two-byte Big5 code: the tiers the generator
# grants full prefix expansion to. Restated here so the shipped table is checked
# against the plain definition of "common", not against the tool's own table.
BIG5_COMMON_PLANES = ((0xA440, 0xC67F), (0xC940, 0xF9D6))


def is_common_plane(char):
    """True for a character in the Big5 常用/次常用 planes."""
    try:
        code = int(char.encode("big5").hex(), 16)
    except UnicodeEncodeError:
        return False
    return any(low <= code < high for low, high in BIG5_COMMON_PLANES)


class ShippedStrokeTableTests(unittest.TestCase):
    """The committed pair the engine actually loads: cin/CnsStroke.cin and its json/ twin."""

    @classmethod
    def setUpClass(cls):
        with open(CIN_PATH, encoding="utf-8") as handle:
            text = handle.read()
        cls.heads, cls.keynames, cls.chardefs = parse_cin(text)
        cls.text = text

    def test_committed_table_carries_the_attribution_exhibit(self):
        """The licence is void without it, so it must survive into the commit."""
        for line in ATTRIBUTION_EXHIBIT:
            self.assertIn(line + "\n", self.text, "missing 顯名聲明 line: %r" % line)

    def test_committed_table_uses_only_the_five_stroke_keys(self):
        self.assertTrue(self.chardefs, "the committed table has no chardefs at all")
        for key, candidates in self.chardefs.items():
            self.assertTrue(key, "empty stroke key")
            self.assertLessEqual(set(key), FIVE_STROKE_KEYS,
                                 "key %r left the Five-stroke alphabet" % key)
            self.assertTrue(candidates, "key %r has no candidate" % key)
        self.assertEqual(self.heads.get("%selkey"), "1234567890")
        self.assertEqual(self.keynames,
                         {"h": "一", "s": "丨", "p": "丿", "n": "丶", "z": "乙"})

    def test_no_committed_code_exceeds_the_stroke_cap(self):
        for key in self.chardefs:
            self.assertLessEqual(len(key), 30, "key %r exceeds maxCharLength" % key)

    def test_common_plane_codes_are_prefix_closed(self):
        """Every Big5-plane character is reachable after any number of its strokes."""
        keys = set(self.chardefs)
        checked = 0
        for key, candidates in self.chardefs.items():
            for char in candidates:
                if not is_common_plane(char):
                    continue
                checked += 1
                for length in range(1, len(key) + 1):
                    self.assertIn(key[:length], keys,
                                  "prefix %r of %r is not a key" % (key[:length], key))
        self.assertGreater(checked, 150000,
                           "the closure check stopped covering the common planes")

    def test_sampled_characters_carry_their_cns_sequences(self):
        """Sampled characters sit under exactly the keys their stroke order implies."""
        for char, sequence in SAMPLED_CNS_SEQUENCES.items():
            key = "".join(DIGIT_TO_KEY[digit] for digit in sequence)
            self.assertIn(char, self.chardefs.get(key, []),
                          "%s is missing from its own code %r" % (char, key))
            expected = ({key[:length] for length in range(1, len(key) + 1)}
                        if is_common_plane(char) else {key})
            found = {k for k, candidates in self.chardefs.items() if char in candidates}
            self.assertEqual(found, expected,
                             "%s is not reachable exactly where its strokes lead" % char)

    def test_runtime_json_stays_in_the_committed_size_class(self):
        """The budget note: not grossly bigger than the largest committed table."""
        size = os.path.getsize(RUNTIME_JSON)
        others = [
            os.path.getsize(os.path.join(JSON_DIR, name))
            for name in os.listdir(JSON_DIR)
            if name.endswith(".json") and name != os.path.basename(RUNTIME_JSON)
        ]
        self.assertTrue(others, "no other committed table to compare against")
        self.assertLessEqual(
            size, int(max(others) * 1.5),
            "json/CnsStroke.json is %d bytes, past the largest committed table; "
            "tighten CLOSURE_TIERS/FULLCODE_TIERS in the generator" % size)

    def test_repertoire_covers_the_big5_and_ext_a_planes(self):
        """A pruning rule that shaved the repertoire away must fail here."""
        characters = {c for candidates in self.chardefs.values() for c in candidates}
        self.assertGreaterEqual(len(characters), 25000,
                                "the table lost its common-plane repertoire")

    def test_committed_candidate_order_matches_the_runtime_json(self):
        """The converter mirrors the .cin order; a drifted ladder copy shows up here.

        render_cin sorts by the CHARSET_LADDER copied from cintojson.py, so the two
        committed artifacts must agree key for key. A reorder in the converter's
        mergeDicts makes this fail instead of quietly changing candidate order.
        """
        with open(RUNTIME_JSON, encoding="utf-8") as handle:
            runtime = json.load(handle)["chardefs"]
        self.assertEqual(set(runtime), set(self.chardefs),
                         "cin/ and json/ no longer hold the same keys")
        for key, candidates in self.chardefs.items():
            self.assertEqual(runtime[key], candidates,
                             "candidate order of key %r differs between the "
                             "committed .cin and the runtime .json" % key)


if __name__ == "__main__":
    unittest.main()

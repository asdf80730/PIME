"""#445: the python backend's error log is size-bounded and rotates.

``python/server.py`` used to open ``%LOCALAPPDATA%\\PIME\\Logs\\python_backend.log``
in append mode for every message, so a long-running session grew the file without
a limit. It now writes through ``logging.handlers.RotatingFileHandler`` with the
two constants the module publishes, which caps the whole log folder at
``LOG_BACKUP_COUNT + 1`` files and that many ``LOG_MAX_BYTES`` in total.

The measured counts are asserted here rather than eyeballed: one file after the
first write, the full bounded chain after a flood, and no file above the byte
bound. See ``librime``'s module docstring for the matching rime-side retention
policy (same ticket).

Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
SPDX-License-Identifier: LGPL-2.1-or-later
"""

import os
import sys
import tempfile
import unittest
from unittest import mock

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), os.path.pardir))
PYTHON_DIR = os.path.join(ROOT, "python")
if PYTHON_DIR not in sys.path:
    sys.path.insert(0, PYTHON_DIR)

import server as server_module  # noqa: E402 - imported after the path is set up

# A payload sized so the flood crosses LOG_MAX_BYTES four times: the chain is
# full and every backup is in place. The arithmetic is derived from the module's
# own values, so a changed bound is reflected here automatically.
LINE_LENGTH = 4000
FLOOD_ROUNDS = (server_module.LOG_MAX_BYTES // (LINE_LENGTH + 1)) * (3 + 1) + 5


class BackendLogRotationTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        patcher = mock.patch.dict(os.environ, {"LOCALAPPDATA": self.tmp.name})
        patcher.start()
        self.addCleanup(patcher.stop)
        self.log_dir = os.path.join(self.tmp.name, "PIME", "Logs")

    def log_files(self):
        if not os.path.isdir(self.log_dir):
            return []
        return sorted(os.listdir(self.log_dir))

    def test_append_error_log_creates_a_single_file(self):
        server_module.append_error_log("first line")

        self.assertEqual(self.log_files(), ["python_backend.log"])
        with open(os.path.join(self.log_dir, "python_backend.log"),
                  encoding="utf-8") as handle:
            self.assertEqual(handle.read(), "first line\n")

    def test_message_without_a_newline_is_terminated(self):
        server_module.append_error_log("no trailing newline")
        server_module.append_error_log("second\n")

        with open(os.path.join(self.log_dir, "python_backend.log"),
                  encoding="utf-8") as handle:
            self.assertEqual(handle.read(),
                             "no trailing newline\nsecond\n")

    def test_flood_rotates_and_caps_the_file_chain(self):
        before = None
        server_module.append_error_log("start")
        before = len(self.log_files())
        self.assertEqual(before, 1, "the first write leaves exactly one file")

        line = "E" * LINE_LENGTH
        for _ in range(FLOOD_ROUNDS):
            server_module.append_error_log(line)

        files = self.log_files()
        # The active file plus LOG_BACKUP_COUNT numbered backups, no more.
        self.assertEqual(len(files), server_module.LOG_BACKUP_COUNT + 1)
        self.assertEqual(files, ["python_backend.log"] + [
            "python_backend.log.%d" % index
            for index in range(1, server_module.LOG_BACKUP_COUNT + 1)])

        total = 0
        for name in files:
            size = os.path.getsize(os.path.join(self.log_dir, name))
            with self.subTest(log=name):
                self.assertLessEqual(size, server_module.LOG_MAX_BYTES)
            total += size
        self.assertLessEqual(total,
                             (server_module.LOG_BACKUP_COUNT + 1) *
                             server_module.LOG_MAX_BYTES)

    def test_newest_file_holds_the_latest_records(self):
        for index in range(FLOOD_ROUNDS):
            server_module.append_error_log(
                ("%d " % index).ljust(LINE_LENGTH, "0"))
        last = FLOOD_ROUNDS - 1

        with open(os.path.join(self.log_dir, "python_backend.log"),
                  encoding="utf-8") as handle:
            lines = handle.read().splitlines()

        self.assertEqual(lines[-1], ("%d " % last).ljust(LINE_LENGTH, "0"))
        # Older records survive in the numbered backups, not in the active file.
        with open(os.path.join(self.log_dir, "python_backend.log.1"),
                  encoding="utf-8") as handle:
            self.assertTrue(handle.read().splitlines())

    def test_documented_policy_matches_the_constants(self):
        documented = server_module.__doc__ or ""
        self.assertIn(str(server_module.LOG_MAX_BYTES), documented)
        self.assertIn(str(server_module.LOG_BACKUP_COUNT), documented)

    def test_log_failure_does_not_break_the_caller(self):
        # No exception may escape: every protocol path calls this inline.
        with mock.patch("os.makedirs", side_effect=OSError(28, "full")):
            self.assertIsNone(server_module.append_error_log("quiet"))
        self.assertEqual(self.log_files(), [])


if __name__ == "__main__":
    unittest.main()

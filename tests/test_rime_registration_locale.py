"""Registration-locale coverage for the Rime (中州韻) profiles (#481).

The TSF registration data in each backend's ``rime/ime.json`` decides which
Windows locale bucket 中州韻輸入法 appears under in the language list:
``PIMETextService/DllEntry.cpp`` (``langProfileFromJson``) reads
``locale``/``fallbackLocale``, and ``libIME2/ImeModule.cpp`` resolves them
with ``LocaleNameToLCID``, retrying the RFC 1766 fallback only when the
primary name does not convert. A Traditional-Chinese user must find the
profile without enabling Simplified Chinese, so every rime profile must land
in the zh-TW lang profile (LANGID 0x0404) whichever resolver branch runs.

Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
SPDX-License-Identifier: LGPL-2.1-or-later
"""
import ctypes
import json
import os
import unittest

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), os.path.pardir))

# The same IME ships as one profile per backend; both are registration data.
RIME_PROFILES = [
    os.path.join(ROOT, "python", "input_methods", "rime", "ime.json"),
    os.path.join(ROOT, "go-backend", "input_methods", "rime", "ime.json"),
]

# LANGID of zh-TW per MS-LCID — the Traditional-Chinese bucket PIME's other
# IMEs register in; go-backend/meow is the known outlier (ticket 24).
LANGID_ZH_TW = 0x0404


def load_profile(path):
    with open(path, encoding="utf-8") as fp:
        return json.load(fp)


class RimeRegistrationLocaleTests(unittest.TestCase):
    def test_locale_tags_are_traditional_chinese(self):
        # PIME's Traditional-Chinese IMEs (python/, node/, the python meow)
        # all declare zh-Hant-TW / zh-TW; rime must not drift back to the
        # zh-Hans-CN / zh-CN that shipped since #481.
        for path in RIME_PROFILES:
            with self.subTest(profile=path):
                profile = load_profile(path)
                self.assertEqual(profile["locale"], "zh-Hant-TW")
                self.assertEqual(profile["fallbackLocale"], "zh-TW")

    @unittest.skipUnless(hasattr(ctypes, "windll"),
                         "needs the Windows kernel32 locale resolver")
    def test_registration_langid_is_traditional_chinese(self):
        kernel32 = ctypes.windll.kernel32

        def resolve(tag):
            return kernel32.LocaleNameToLCID(tag, 0) & 0xFFFF

        for path in RIME_PROFILES:
            profile = load_profile(path)
            with self.subTest(profile=path, field="locale"):
                # Same resolution order as ImeModule.cpp: the primary locale
                # name, and only the fallback when it fails to convert.
                lcid = resolve(profile["locale"])
                if lcid == 0 and profile["fallbackLocale"]:
                    lcid = resolve(profile["fallbackLocale"])
                self.assertEqual(lcid, LANGID_ZH_TW)
            with self.subTest(profile=path, field="fallbackLocale"):
                # On builds where the RFC 4646 name does not convert, the
                # fallback alone must still land in the Traditional bucket.
                self.assertEqual(resolve(profile["fallbackLocale"]),
                                 LANGID_ZH_TW)


if __name__ == "__main__":
    unittest.main()

"""Registration-locale coverage for the Rime (中州韻) and Meow (喵喵) profiles.

The TSF registration data in each backend's ``input_methods/<ime>/ime.json``
decides which Windows locale bucket an IME appears under in the language
list: ``PIMETextService/DllEntry.cpp`` (``langProfileFromJson``) reads
``locale``/``fallbackLocale``, and ``libIME2/ImeModule.cpp`` resolves them
with ``LocaleNameToLCID``, retrying the RFC 1766 fallback only when the
primary name does not convert. A Traditional-Chinese user must find every
PIME IME without enabling Simplified Chinese, so each profile must land in
the zh-TW lang profile (LANGID 0x0404) whichever resolver branch runs.

Rime carried a Simplified-Chinese locale since its 2016 manifest (#481,
fixed by ticket 09); the go backend's 喵喵 copy shipped the same pair, inherited
from the rime manifest it was written against rather than from its own
node/python twins, and ticket 24 adjudicated it a defect. One IME registers
as one profile per backend, so the twins of an IME must agree on one pair.
The rime manifest now adds a second profile of its own for zh-CN
(LANGID 0x0804): ``langProfileFromJson`` turns each ``additionalProfiles``
entry into one more ``AddLanguageProfile`` call under the same CLSID, so
Simplified and Traditional Chinese users both find 中州韻輸入法.

The same pair of rime files also carries the profile side of #403: beside the
manifest checks, ``RimeProfileAppOptionsTests`` keeps the commented
``app_options`` example in ``python/input_methods/rime/data/PIME.yaml`` naming
exactly the option keys the parser applies to a session.

Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
SPDX-License-Identifier: LGPL-2.1-or-later
"""
import ctypes
import json
import os
import sys
import unittest

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), os.path.pardir))

# The same IME ships as one profile per backend; all are registration data.
RIME_PROFILES = [
    os.path.join(ROOT, "python", "input_methods", "rime", "ime.json"),
    os.path.join(ROOT, "go-backend", "input_methods", "rime", "ime.json"),
]

MEOW_PROFILES = [
    os.path.join(ROOT, "node", "input_methods", "meow", "ime.json"),
    os.path.join(ROOT, "python", "input_methods", "meow", "ime.json"),
    os.path.join(ROOT, "go-backend", "input_methods", "meow", "ime.json"),
]

# Both pin groups, iterated by the value tests.
ALL_PROFILES = RIME_PROFILES + MEOW_PROFILES

# Every backend whose input_methods tree DllRegisterServer scans — the same
# registry the product reads (PIMEImeModule.cpp), so a fourth backend joins
# the invariant below the day it lands.
with open(os.path.join(ROOT, "backends.json"), encoding="utf-8") as _fp:
    BACKEND_INPUT_METHOD_DIRS = [
        os.path.join(ROOT, entry["workingDir"], "input_methods")
        for entry in json.load(_fp)
        if os.path.isdir(
            os.path.join(ROOT, entry["workingDir"], "input_methods"))
    ]

# LANGID of zh-TW per MS-LCID — the Traditional-Chinese bucket every PIME
# IME registers in.
LANGID_ZH_TW = 0x0404

# LANGID of zh-CN — the second bucket the rime manifest adds itself to, so
# Simplified-Chinese users find 中州韻輸入法 without enabling it.
LANGID_ZH_CN = 0x0804


def load_profile(path):
    with open(path, encoding="utf-8") as fp:
        return json.load(fp)


class RegistrationLocaleTests(unittest.TestCase):
    def test_locale_tags_are_traditional_chinese(self):
        # PIME's Traditional-Chinese IMEs all declare zh-Hant-TW / zh-TW;
        # rime must not drift back to the zh-Hans-CN / zh-CN that shipped
        # since #481, and no meow copy may drift to the pair ticket 24
        # removed from the go copy.
        for path in ALL_PROFILES:
            with self.subTest(profile=path):
                profile = load_profile(path)
                self.assertEqual(profile["locale"], "zh-Hant-TW")
                self.assertEqual(profile["fallbackLocale"], "zh-TW")

    # Probe the platform, not ctypes.windll: other modules in this suite
    # install Win32 shims that make hasattr(ctypes, "windll") true on Linux,
    # and the shim's kernel32 has no LocaleNameToLCID to resolve with
    # (docs/agents/verification.md, probe discipline).
    @unittest.skipUnless(sys.platform == "win32",
                         "needs the Windows kernel32 locale resolver")
    def test_registration_langid_is_traditional_chinese(self):
        kernel32 = ctypes.windll.kernel32

        def resolve(tag):
            return kernel32.LocaleNameToLCID(tag, 0) & 0xFFFF

        for path in ALL_PROFILES:
            profile = load_profile(path)
            with self.subTest(profile=path, field="locale"):
                # Same resolution order as ImeModule.cpp: the primary locale
                # name, and only the fallback when it fails to convert.
                lcid = resolve(profile["locale"])
                if lcid == 0 and profile["fallbackLocale"]:
                    lcid = resolve(profile["fallbackLocale"])
                self.assertEqual(lcid, LANGID_ZH_TW)
            with self.subTest(profile=path, field="fallbackLocale"):
                # On builds where the RFC 4646 name does not convert, the
                # fallback alone must still land in the Traditional bucket.
                self.assertEqual(resolve(profile["fallbackLocale"]),
                                 LANGID_ZH_TW)
            for index, extra in enumerate(profile.get("additionalProfiles", [])):
                with self.subTest(profile=path,
                                  field="additionalProfiles[%d]" % index):
                    lcid = resolve(extra["locale"])
                    if lcid == 0 and extra.get("fallbackLocale"):
                        lcid = resolve(extra["fallbackLocale"])
                    self.assertEqual(lcid, LANGID_ZH_CN)

    def test_rime_adds_the_simplified_chinese_profile(self):
        # The rime engine is used under both Chinese locales, so each copy
        # declares a second profile for zh-CN next to its Traditional one,
        # under its own profile GUID (two AddLanguageProfile calls, one CLSID).
        for path in RIME_PROFILES:
            with self.subTest(profile=path):
                profile = load_profile(path)
                extra = profile.get("additionalProfiles")
                self.assertIsInstance(extra, list)
                self.assertEqual(len(extra), 1, "exactly one extra profile")
                self.assertEqual(extra[0]["locale"], "zh-CN")
                self.assertEqual(extra[0]["fallbackLocale"], "zh-CN")
                self.assertNotEqual(extra[0]["guid"], profile["guid"],
                                    "the second profile needs its own GUID")

    def test_every_profile_entry_carries_a_registration_guid(self):
        # One AddLanguageProfile call per entry, and every dispatcher matches on
        # the entry's own guid, so an entry that names a locale but no guid is a
        # bucket no client can ever activate: the profile shows up in the
        # language list and answers 未知的输入法. Checked per file over every
        # backend tree, because each backend is read by its own dispatcher.
        # Expected shipped counts, so an added profile cannot slip through this
        # loop unnamed: 喵喵輸入法 1 guid in each of the three trees (node,
        # python, go-backend), 中州韻輸入法 2 in python and go-backend (the flat
        # guid plus its zh-CN additionalProfiles entry), emojime 1 in node. The
        # per-tree lookup cases live in the runner that serves each tree:
        # tests/test_service_manager.py for python, node/test/loadServices.test.js
        # for node, go-backend/server_test.go for go.
        # Rule recorded in `docs/adr/0004-per-backend-profile-guids.md`,
        # "Per-backend profile GUIDs; the locale pair is the only cross-twin
        # invariant".
        for base in BACKEND_INPUT_METHOD_DIRS:
            for name in sorted(os.listdir(base)):
                path = os.path.join(base, name, "ime.json")
                if not os.path.isfile(path):
                    continue
                with self.subTest(profile=path):
                    profile = load_profile(path)
                    self.assertTrue(profile.get("guid"),
                                    "the flat guid is what registers the service")
                    seen = [profile["guid"].lower()]
                    for entry in profile.get("additionalProfiles", []):
                        self.assertIsInstance(entry, dict,
                                              "a profile entry is an object")
                        self.assertTrue(entry.get("guid"),
                                        "an additional profile needs its own guid")
                        guid = entry["guid"].lower()
                        self.assertNotIn(guid, seen,
                                         "one guid cannot name two profiles")
                        seen.append(guid)

    def test_twins_agree_on_one_locale_per_ime(self):
        # One IME is one profile per backend: a Windows user must not find
        # 喵喵輸入法 twice under two different locale buckets because a new
        # backend copy drifted from the twins it copied. The invariant
        # guards every multi-backend IME, not just the two adjudicated.
        # The locale pair is the only cross-twin invariant, and the per-file
        # GUID rule beside it is recorded in
        # `docs/adr/0004-per-backend-profile-guids.md`, "Per-backend profile
        # GUIDs; the locale pair is the only cross-twin invariant".
        twins = {}
        for base in BACKEND_INPUT_METHOD_DIRS:
            for name in sorted(os.listdir(base)):
                path = os.path.join(base, name, "ime.json")
                if os.path.isfile(path):
                    profile = load_profile(path)
                    # langProfileFromJson (DllEntry.cpp) defaults both keys
                    # to "" when absent, so mirror the consumer instead of
                    # crashing: an omission becomes a twins disagreement.
                    twins.setdefault(name, []).append(
                        (path, profile.get("locale", ""),
                         profile.get("fallbackLocale", ""),
                         tuple((entry.get("locale", ""),
                                entry.get("fallbackLocale", ""))
                               for entry in profile.get("additionalProfiles", []))))
        for name, copies in twins.items():
            if len(copies) < 2:
                continue
            with self.subTest(ime=name):
                values = {(locale, fallback, extra)
                          for _, locale, fallback, extra in copies}
                self.assertEqual(
                    len(values), 1,
                    "twins disagree on locale: %s" % ", ".join(
                        "%s = %s/%s %s" % copy for copy in copies))


class RimeProfileAppOptionsTests(unittest.TestCase):
    # The two rime tickets land on one pair of files: the manifest read above
    # and the profile read here. The profile's commented example is the only
    # in-tree documentation of the keys the engine honours, so it must name the
    # same ones the parser in librime.py applies to a session (#403).

    PROFILE = os.path.join(ROOT, "python", "input_methods", "rime",
                           "data", "PIME.yaml")

    def app_options_example(self):
        with open(self.PROFILE, encoding="utf-8") as handle:
            lines = [line.rstrip("\n") for line in handle]
        start = None
        for index, line in enumerate(lines):
            if line.lstrip("#").strip().rstrip(":") == "app_options":
                start = index
                break
        self.assertIsNotNone(start, "the profile must show the app_options example")
        block = []
        for line in lines[start + 1:]:
            stripped = line.lstrip("#").strip()
            if not stripped:
                continue
            if not line.startswith("#"):
                break
            block.append(stripped)
        return block

    def test_profile_shows_the_app_options_example(self):
        block = self.app_options_example()
        # One process name with at least one option underneath it.
        self.assertGreaterEqual(len(block), 2)
        self.assertTrue(block[0].endswith(":"), block[0])
        self.assertTrue(any(item.startswith("ascii_mode:") or
                            item.startswith("full_shape:") or
                            item.startswith("ascii_punct:")
                            for item in block[1:]), block)
        # The process key is the plain file name the parser compares against
        # ``os.path.basename(sys.executable).lower()``: no path, no case change,
        # so a host that is not the backend process simply matches nothing.
        name = block[0][:-1].strip()
        self.assertEqual(name, name.lower())
        self.assertNotIn("\\", name)
        self.assertNotIn("/", name)
        self.assertTrue(name.endswith(".exe") or name in ("PIME", "Rime.PIME"), name)

    def test_example_names_only_honoured_keys(self):
        try:
            python_dir = os.path.join(ROOT, "python")
            if python_dir not in sys.path:
                sys.path.insert(0, python_dir)
            from input_methods.rime import librime
        except Exception as error:  # pragma: no cover - Linux without librime.so
            self.skipTest("librime is not installed: %s" % error)
        honoured = {key.decode("utf-8") for key in librime.APP_OPTION_KEYS}
        documented = {item.split(":", 1)[0].strip()
                      for item in self.app_options_example()[1:]}
        self.assertTrue(documented, "the example must carry at least one option")
        self.assertEqual(documented - honoured, set(),
                         "the example documents keys the parser ignores")


if __name__ == "__main__":
    unittest.main()

#!/usr/bin/env bash
# The standing rules (docs/agents/code-review.md) demand an AI declaration in
# every commit message, split three ways by #996. File headers have had a gate
# since the start (check_ai_declarations.sh) and PR bodies since #1013
# (check_pr_bodies.sh); commit messages had none, and PR #1010 shipped two
# commits whose messages carry no declaration without anything noticing.
#
# The declaration is judged on the whole message with newlines folded: the
# supervised form legitimately wraps its second sentence, and a fold that
# anchors on the last line would redd the very form the rules prescribe.
#
# Usage: check_pr_commit_declarations.sh [<branch>|<sha>]   (default: current branch)
#        Stand in the PR worktree or pass the branch name; the commits are read
#        from the repository either way.
# Exit codes: 0 every commit carries a declaration, 1 a commit message has none,
# 125 not applicable (integration or local record branch, detached HEAD without
# an argument, ref is not a commit, no EasyIME/PIME remote).
# tests/check_pr_commit_declarations_test.sh pins these codes; rerun after edits.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later

set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  commit declarations (not inside a git checkout)\n'
    exit 125
}
cd "$ROOT" || exit 1

target=${1:-}
if [ -z "$target" ]; then
    target=${GITHUB_HEAD_REF:-}
fi
if [ -z "$target" ]; then
    target=$(git symbolic-ref --short -q HEAD 2>/dev/null || true)
    [ -n "$target" ] || { printf 'SKIP  commit declarations (detached HEAD, pass a branch)\n'; exit 125; }
fi

case "$target" in
    master|main|local/*|omp/*|win/*)
        printf 'SKIP  commit declarations (%s is an integration or local branch)\n' "$target"
        exit 125
        ;;
esac

base_ref=
for remote in $(git remote); do
    case "$(git config --get "remote.$remote.url" || true)" in
        *EasyIME/PIME*) base_ref="$remote/master"; break ;;
    esac
done
if [ -z "$base_ref" ]; then
    printf 'SKIP  commit declarations (no EasyIME/PIME remote; add it and fetch first)\n'
    exit 125
fi
git rev-parse --verify --quiet "$base_ref" >/dev/null || {
    printf 'SKIP  commit declarations (%s absent; git fetch %s first)\n' "$base_ref" "${base_ref%/*}"
    exit 125
}
git rev-parse --verify --quiet "$target^{commit}" >/dev/null || {
    printf 'SKIP  commit declarations (%s is not a commit)\n' "$target"
    exit 125
}

# The three #996 forms, matched on the whole message with newlines folded so a
# wrapped "Implementation generated with AI assistance from …" counts.
decl='Architecture and design by|Design and decision by|Fully generated by|Generated with assistance from|Implementation generated with AI assistance from'

bad=0
checked=0
for c in $(git rev-list "$base_ref..$target"); do
    checked=$((checked + 1))
    folded=$(git log -1 --format=%B "$c" | tr '\n\r' '  ')
    if ! printf '%s' "$folded" | grep -Eq "$decl"; then
        printf 'FAIL  commit declarations: %s has no AI declaration line\n' \
            "$(git rev-parse --short "$c")"
        printf '  subject: %s\n' "$(git log -1 --format=%s "$c")"
        bad=1
    fi
done

if [ "$bad" -eq 1 ]; then
    printf 'Append one of the three forms as the message tail — they live in the\n'
    printf 'standing rules of docs/agents/code-review.md. A maintainer reading a\n'
    printf 'silent message cannot tell supervised work from autonomous work.\n'
    exit 1
fi
printf 'PASS  commit declarations (%s commit(s) beyond %s each carry an AI declaration)\n' \
    "$checked" "$base_ref"

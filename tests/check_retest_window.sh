#!/usr/bin/env bash
# The 25 stale-unreproducible issues got a bilingual retest request with a
# stated silence window (census §4.5), and the close-on-silence rule is only
# real if something reads it after the window shuts. The window and the rule
# live in a comment body on 25 upstream threads plus the census paragraph, so
# this is the one place that can answer "did the sweep run" on the day after.
#
# Four things are compared:
#   - the issue numbers the §4.5 outcomes table names, against the count in its
#     own heading;
#   - each numbered issue's live `state` off the REST issues endpoint;
#   - the window's expiry date, off the same section;
#   - after the expiry, each still-open thread's last comment id against the id
#     the table recorded, which is the retest request itself.
#
# A silent issue still open past the expiry is the miss: the rule says close it
# as `unable to reproduce`. An issue with a later comment is a reporter reply
# and stays open by design.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later
#
# Usage: check_retest_window.sh [<census.md>]
# Exit codes: 0 the sweep is settled, 1 a silent issue is still open (or the
# table is inconsistent), 125 not applicable (no checkout, no census section,
# or no `gh` on this box).

set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  retest window (not inside a git checkout)\n'
    exit 125
}
cd "$ROOT" || exit 1

census=${1:-docs/research/upstream-bug-backlog-2026-10.md}
[ -f "$census" ] || {
    printf 'SKIP  retest window (%s absent)\n' "$census"
    exit 125
}
# `GH_BIN` lets the self-test point at a stub; a box without the CLI still
# answers 125 rather than a red.
gh_bin=${GH_BIN:-gh}
command -v "$gh_bin" >/dev/null 2>&1 || {
    printf 'SKIP  retest window (no gh on PATH)\n'
    exit 125
}

REPO=EasyIME/PIME

# The §4.5 block: heading count, the expiry date, and the issue/comment-id
# pairs of the outcomes table. The table is five `| # | comment |` pairs per
# row line, so the pairs come out of every cell of every row.
section=$(awk '/^### 4\.5 /{f=1} f{print} /^### 4\.6 /{exit}' "$census")
[ -n "$section" ] || {
    printf 'SKIP  retest window (no census §4.5 in %s)\n' "$census"
    exit 125
}

claim=$(printf '%s\n' "$section" | awk '/^### 4\.5 /{
    if (match($0, /\(([0-9]+)\)/)) print substr($0, RSTART+1, RLENGTH-2)
}')
expiry=$(printf '%s\n' "$section" | awk '{
    if (match($0, /expiring [0-9]{4}-[0-9]{2}-[0-9]{2}/)) {
        print substr($0, RSTART+9, 10); exit
    }
}')
pairs=$(printf '%s\n' "$section" | awk -F'|' '
    /^\| *[0-9]+ *\| *[0-9]+ *\|/ {
        for (i = 2; i <= NF; i++) {
            v = $i; gsub(/[[:space:]]/, "", v)
            if (v != "") cell[++n] = v
        }
    }
    END { for (i = 1; i + 1 <= n; i += 2) print cell[i], cell[i+1] }
')

[ -n "$pairs" ] || {
    printf 'FAIL  retest window: §4.5 carries no issue/comment-id rows\n'
    exit 1
}
[ -n "$expiry" ] || {
    printf 'FAIL  retest window: §4.5 states no expiry date for its silence window\n'
    exit 1
}

count=$(printf '%s\n' "$pairs" | awk 'NF{c++} END{print c+0}')
if [ -n "$claim" ] && [ "$claim" != "$count" ]; then
    printf 'FAIL  retest window: §4.5 heading says %s issue(s), its table rows carry %s\n' \
        "$claim" "$count"
    exit 1
fi

# Live states, one paginated call for the whole repo.
states=$("$gh_bin" api --paginate "repos/$REPO/issues?state=all&per_page=100" \
    --jq '.[] | "\(.number) \(.state)"' 2>/dev/null)
if [ -z "$states" ]; then
    printf 'SKIP  retest window (gh api returned no issues for %s)\n' "$REPO"
    exit 125
fi

today=$(date +%Y-%m-%d)
closed=0
open_seen=0
replied=0
bad=0

state_of() { # number
    printf '%s\n' "$states" | awk -v n="$1" '$1 == n { print $2; found = 1; exit } END { if (!found) print "missing" }'
}

while read -r number comment_id; do
    [ -n "$number" ] || continue
    state=$(state_of "$number")
    if [ "$state" = "missing" ]; then
        printf 'FAIL  retest window: §4.5 names #%s and %s has no such issue\n' "$number" "$REPO"
        bad=1
        continue
    fi
    if [ "$state" = "closed" ]; then
        closed=$((closed + 1))
        continue
    fi
    open_seen=$((open_seen + 1))
    if [ "$today" \< "$expiry" ]; then
        continue    # window still open: an open issue is the expected state
    fi
    last=$("$gh_bin" api "repos/$REPO/issues/$number/comments" --jq '.[-1].id' 2>/dev/null)
    if [ -z "$last" ]; then
        printf 'FAIL  retest window: #%s open with no readable comment list\n' "$number"
        bad=1
        continue
    fi
    if [ "$last" = "$comment_id" ]; then
        printf 'FAIL  retest window: #%s still open on %s with the retest request %s as its last comment (silent, so close it)\n' \
            "$number" "$today" "$comment_id"
        bad=1
    else
        replied=$((replied + 1))
    fi
done <<< "$pairs"

if [ "$bad" -ne 0 ]; then
    printf 'FAIL  retest window (%s issue(s), window closed %s)\n' "$count" "$expiry"
    exit 1
fi

if [ "$today" \< "$expiry" ]; then
    printf 'PASS  retest window (%s issue(s), %s closed, %s open, window runs to %s)\n' \
        "$count" "$closed" "$open_seen" "$expiry"
else
    printf 'PASS  retest window (%s issue(s), %s closed, %s open with a reporter reply, window closed %s)\n' \
        "$count" "$closed" "$replied" "$expiry"
fi
exit 0

#!/usr/bin/env bash
# The standing rules in docs/agents/code-review.md put the AI declaration at
# the end of the message, and the body is pasted by hand: a missing last line
# makes the human add it.
# #996 split the declaration three ways; the pre-#996 one-liner is still
# accepted for bodies written before it and posted already.
#
# Both gates run this script: tests/run_local_tests.sh (Linux and CI) and
# tests/verify_windows.sh. The body file is written on the box that delivers
# the PR, and .scratch/ is gitignored, so no CI job can ever read a draft —
# the check has to live where the drafts are. PR_BODY judges one draft
# outside .scratch without moving it.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later

set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  PR bodies (not inside a git checkout)\n'
    exit 125
}
cd "$ROOT" || exit 1

files=()
[ -d .scratch ] && mapfile -t files < <(find .scratch -maxdepth 1 -type f -name 'pr-*-body.md' -print)
bad=0
if [ -n "${PR_BODY:-}" ]; then
    if [ -f "$PR_BODY" ]; then
        files+=("$PR_BODY")
    else
        printf 'PR_BODY is not a file: %s\n' "$PR_BODY"
        bad=1
    fi
fi
for f in "${files[@]}"; do
    last=$(awk 'NF { line = $0 } END { print line }' "$f")
    # §2's human-designed form is "<design phrase> by <Author>. Implementation
    # generated with AI assistance from <Agent> (<Model>)." — match either half
    # rather than one wording of the design phrase: PR #1005 declares "Design
    # and decision by", which names the human role just as well. The match is
    # anchored to the last non-blank line on purpose: a declaration wrapped
    # across two lines leaves that line a model-name fragment, which is how a
    # 2026-10 body shipped past a gate that only ran on the other box.
    if ! printf '%s' "$last" | grep -Eq \
        '^(Architecture and design by|Design and decision by|Fully generated by|Generated with assistance from)|Implementation generated with AI assistance from'; then
        printf 'missing AI declaration: %s\n' "$f"
        bad=1
    fi
    # upstream-pr.md: merged PRs carry no generic-template headings. The
    # /pr skill's Summary/Evidence/Merge Danger scaffold is the shape most
    # likely to be pasted, so name it.
    if grep -Eq '^## (Summary|Evidence|Merge Danger)[[:space:]]*$' "$f"; then
        printf 'generic template headings in %s; follow docs/agents/upstream-pr.md\n' "$f"
        bad=1
    fi

    # The body is pasted into GitHub by hand, so what a bad edit leaves behind is
    # what the maintainer reads: one paragraph emitted twice reads as intentional.
    dup=$(awk 'length($0) > 60 { c[$0]++ } END { for (l in c) if (c[l] > 1) { print l; exit } }' "$f")
    if [ -n "$dup" ]; then
        printf 'duplicated paragraph in %s: %s\n' "$f" "${dup:0:70}"
        bad=1
    fi

    # A Validation: line names the runs that earned the PR its evidence; a
    # command path no tree and no ref has ever carried is credit taken before
    # the sale (docs/agents/upstream-pr.md). PR_BODY_SKIP_PATHS=1 waives the
    # rule for a body that legitimately cites a path this branch deletes.
    if [ "${PR_BODY_SKIP_PATHS:-0}" != 1 ]; then
        while read -r cited; do
            [ -n "$cited" ] || continue
            # A citation may carry a line range (`main.rs:143,146`) and may be
            # written relative to the module it lives under, so a trailing
            # segment or a directory both count as the same fact.
            cited=${cited%%:*}
            [ -e "$cited" ] && continue
            [ -n "$(git ls-files -- "$cited" "*$cited" "*$cited/*" | head -n 1)" ] && continue
            if ! git log --all --format= --name-only -- "$cited" "*$cited" "*$cited/*" 2>/dev/null \
                    | head -n 1 | grep -q .; then
                printf 'Validation: cites a path no tree or ref carries: %s (%s)\n' "$cited" "$f"
                bad=1
            fi
        done < <(awk '{ t = tolower($0); gsub(/[*_` ]/, "", t)
                        if (t == "validation:") v = 1 } v' "$f" \
                    | grep -oE '`[^` ]+/[^`]*`' | grep -v '://' | tr -d '`' | sort -u)
    fi
done
printf 'checked %d PR bodies\n' "${#files[@]}"
[ "$bad" -eq 0 ]

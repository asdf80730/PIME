#!/usr/bin/env bash
# Regression test for tests/check_closeout_identifiers.sh. The gate's value is that
# it reads each backticked token independently of the prose around it, so the pairs
# it must distinguish are: a ticket whose identifiers resolve (green) against the
# same ticket with one SHA mistyped (red, naming the token), a pin whose only home
# is an extra object directory (green while that directory is passed, and the
# unchecked third state once it is not), a `#N` that no tracker answers (still
# green, counted unchecked), and a scratch dir with no ticket files (not applicable).
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later

set -u

root=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  close-out identifiers self-test (not inside a git checkout)\n'
    exit 125
}
check=$root/tests/check_closeout_identifiers.sh
if [ ! -f "$check" ]; then
    printf 'FAIL  close-out identifiers self-test (no %s)\n' "$check"
    exit 1
fi

# Not a bare /tmp: MSYS child shells default TMP/TEMP to /tmp, and native
# git.exe then maps a /tmp argument to C:\tmp while bash sees %TEMP%.
if command -v cygpath >/dev/null 2>&1 && [ -n "${USERPROFILE:-}" ]; then
    tmpbase=$(cygpath -u "$USERPROFILE")
else
    tmpbase=${TMPDIR:-/tmp}
fi
tmp=$(mktemp -d "$tmpbase/pime-closeout-identifiers-selftest.XXXXXX")
sandbox=$tmp/repo
plain=$tmp/plain
mkdir -p "$sandbox/.scratch/feat/issues" "$plain"

cleanup() {
    rm -rf "$tmp"
}
trap cleanup EXIT

git -C "$sandbox" init -q >/dev/null
printf 'x\n' > "$sandbox/f.txt"
git -C "$sandbox" add f.txt >/dev/null
git -C "$sandbox" -c user.email=t@example.com -c user.name=t commit -q -m 'seed' >/dev/null
head_sha=$(git -C "$sandbox" rev-parse HEAD)
short_sha=${head_sha:0:7}

failures=0

# expect <want> <name> [extra args...] — runs the gate over the sandbox scratch dir.
expect() {
    local want=$1 name=$2; shift 2
    local out rc
    out=$(bash "$check" "$sandbox/.scratch" "$@" 2>&1)
    rc=$?
    if [ "$rc" -ne "$want" ]; then
        printf 'FAIL  %s (rc %s, want %s)\n%s\n' "$name" "$rc" "$want" "$out"
        failures=$((failures + 1))
    fi
}

# expect_says <name> <fragment> [extra args...] — the miss has to be named.
expect_says() {
    local name=$1 fragment=$2; shift 2
    local out
    out=$(bash "$check" "$sandbox/.scratch" "$@" 2>&1)
    if ! printf '%s' "$out" | grep -q -- "$fragment"; then
        printf 'FAIL  %s (no "%s" in output)\n%s\n' "$name" "$fragment" "$out"
        failures=$((failures + 1))
    fi
}

ticket=$sandbox/.scratch/feat/issues/01-close.md
write_ticket() {
    cat > "$ticket" <<EOF
# 01: sample close-out

Status: resolved

- [x] done

## Comments

Fixed by PR #999 (merge commit \`$short_sha\`), the pin \`$short_sha\`, the run id
\`42987775056\` and the date \`20260805\`.

*(Comment generated with AI assistance from omp (tensorfold/Qwen3.8-Flash-Next))*
EOF
}

write_ticket
expect 0 'identifiers that resolve in the given object dir are green' \
    "$sandbox"
expect_says 'the ambiguous bare digit strings are only counted' 'unchecked' \
    "$sandbox"

# A mistyped SHA reddens and names the token.
sed -E "s/\`$short_sha\`/\`$short_sha$short_sha\`/" "$ticket" > "$ticket.n" && \
    mv "$ticket.n" "$ticket"
expect 1 'a mistyped SHA reddens' "$sandbox"
expect_says 'the mistyped token is named' "$short_sha$short_sha" "$sandbox"

# The third state: no fetched object dir beside the superproject leaves the same
# pin unchecked instead of red.
write_ticket
expect 0 'an unfetched object dir leaves its pin unchecked' "$plain"

# No ticket files at all is not applicable.
rm -f "$ticket"
expect 125 'a scratch dir with no tickets is not applicable' "$sandbox"

printf '%d failed\n' "$failures"
[ "$failures" -eq 0 ]

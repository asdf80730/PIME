#!/usr/bin/env bash
# A product PR branch carries product files only (docs/agents/upstream-pr.md), so
# its commit messages must promise nothing the branch does not contain.
#
# The defect this pins: cutting the PR branch with `git cherry-pick -n <sha>` plus
# `git commit -C <sha>` copies the integration-branch message along with its
# "the new test drives the handler…" and "registers … in the parse check"
# sentences. The upstream reviewer then looks for `tests/` files that exist only
# on the integration branch, and the PR reads as claiming work it never shipped.
#
# Only a commit that carries no `tests/` path is judged, so a branch that really
# does ship the test may still describe it.
#
# Usage: check_pr_commit_claims.sh [<branch>|<sha>]   (default: current branch)
#        Stand in the PR worktree or pass the branch name; the diff is read from
#        the repository either way.
# Exit codes: 0 every message matches its own diff, 1 a message claims a test or
# gate change the commit does not carry, 125 not applicable (integration or local
# record branch, detached HEAD without an argument, ref is not a commit, no
# EasyIME/PIME remote).
# tests/check_pr_commit_claims_test.sh pins these codes; rerun it after edits.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later

set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  commit claims (not inside a git checkout)\n'
    exit 125
}
cd "$ROOT" || exit 1

target=${1:-}
if [ -z "$target" ]; then
    target=${GITHUB_HEAD_REF:-}
fi
if [ -z "$target" ]; then
    target=$(git symbolic-ref --short -q HEAD 2>/dev/null || true)
    [ -n "$target" ] || { printf 'SKIP  commit claims (detached HEAD, pass a branch)\n'; exit 125; }
fi

case "$target" in
    master|main|local/*|omp/*|win/*)
        printf 'SKIP  commit claims (%s is an integration or local branch)\n' "$target"
        exit 125
        ;;
esac

base_ref=
for remote in $(git remote); do
    case "$(git config --get "remote.$remote.url" || true)" in
        *EasyIME/PIME*) base_ref="$remote/master"; break ;;
    esac
done
if [ -z "$base_ref" ]; then
    printf 'SKIP  commit claims (no EasyIME/PIME remote; add it and fetch first)\n'
    exit 125
fi
git rev-parse --verify --quiet "$base_ref" >/dev/null || {
    printf 'SKIP  commit claims (%s absent; git fetch %s first)\n' "$base_ref" "${base_ref%/*}"
    exit 125
}
git rev-parse --verify --quiet "$target^{commit}" >/dev/null || {
    printf 'SKIP  commit claims (%s is not a commit)\n' "$target"
    exit 125
}

# What a harness commit says about itself. Two shapes: the named artefacts that
# live on the integration branch, and a claim to have added or registered a test.
# Prose about testing ("Tested on Windows 11 x64") matches neither, so a product
# commit stays free to describe the machine it was tried on.
claims='tests/|test suite|parse check|verify_windows|run_local_tests|check_pr_|check_tracker|check_scratch|cargo fmt|cargo clippy|green gate|CI (wiring|green|job|step|check)|\b(adds?|added|new|register(s|ed)?|ships?|includes?|comes with)\b[^.]{0,40}\btests?\b'

bad=0
checked=0
for c in $(git rev-list "$base_ref..$target"); do
    files=$(git show --name-only --format= "$c")
    if printf '%s\n' "$files" | grep -q '^tests/'; then
        continue
    fi
    checked=$((checked + 1))
    line=$(git log -1 --format=%B "$c" | grep -Ei "$claims" | head -n 1 || true)
    if [ -n "$line" ]; then
        printf 'FAIL  commit claims: %s describes a test or gate change it does not carry\n' \
            "$(git rev-parse --short "$c")"
        printf '  subject: %s\n' "$(git log -1 --format=%s "$c")"
        printf '  claims:  %s\n' "$line"
        printf '  files:   %s\n' "$(printf '%s' "$files" | tr '\n' ' ')"
        bad=1
    fi
done

if [ "$bad" -eq 1 ]; then
    printf 'Reword each message to the product change the commit actually holds.\n'
    printf 'The harness copy of the test stays on the integration branch; naming it here\n'
    printf 'asks an upstream reviewer to look for a file the PR never carried.\n'
    exit 1
fi
printf 'PASS  commit claims (%s commit(s) beyond %s describe only their own diff)\n' \
    "$checked" "$base_ref"

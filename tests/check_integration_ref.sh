#!/usr/bin/env bash
# Which branch is the integration ref? More than one `local/*` record branch can
# carry the harness at once, and the two can diverge — measured 2026-10-30, one
# box held `local/linux-master` and `local/stroke-parked` with 37 and 31 unique
# commits and different copies of docs/agents plus both gate scripts. A session
# that commits by remembered name then lands on the history lacking the harness
# it just read, so the ambiguity is printed at gate time instead of discovered
# mid-delivery (docs/agents/shared-checkout.md).
#
# Informational by design: it names the candidates and exits 0 either way, so a
# parked branch can never redden the gate.
#
# Usage: check_integration_ref.sh   (run from any checkout)
# Exit codes: 0 always, 125 not applicable (not inside a git checkout).
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later

set -u

git rev-parse --show-toplevel >/dev/null 2>&1 || {
    printf 'SKIP  integration ref (not inside a git checkout)\n'
    exit 125
}

head_ref=$(git rev-parse --abbrev-ref HEAD 2>/dev/null || true)
carriers=()
while read -r ref; do
    [ -n "$ref" ] || continue
    branch=${ref#refs/heads/}
    case "$branch" in
        master|main) ;;
        *)
            if git ls-tree --name-only "$branch" -- docs/agents GLOSSARY.md 2>/dev/null \
                    | head -n 1 | grep -q .; then
                carriers+=("$branch")
            fi
            ;;
    esac
done < <(git for-each-ref --format='%(refname)' refs/heads/)

if [ ${#carriers[@]} -eq 0 ]; then
    printf 'OK    integration ref (no local record branch carries the harness)\n'
    exit 0
fi

if [ ${#carriers[@]} -eq 1 ]; then
    printf 'OK    integration ref: %s%s\n' "${carriers[0]}" \
        "$([ "${carriers[0]}" = "$head_ref" ] && printf ' (checked out)' || printf ' — not checked out')"
    exit 0
fi

printf 'WARN  %s local record branches carry the harness; commit by the checked-out ref, not by name\n' "${#carriers[@]}"
for branch in "${carriers[@]}"; do
    tip=$(git log -1 --format='%h %cd' --date=short "$branch")
    marker='  '
    [ "$branch" = "$head_ref" ] && marker='->'
    printf '  %s %-26s %s\n' "$marker" "$branch" "$tip"
done
printf '      merge one into the other, or the gates and agent docs keep differing by branch.\n'
exit 0

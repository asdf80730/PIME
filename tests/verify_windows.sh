#!/usr/bin/env bash
# Local verification for this Windows checkout (native, no Wine, no WSL).
#
# Every tool lives under .tools/ inside the project (see .tools/env.sh); this
# script only puts those directories on PATH for the duration of the run and
# touches nothing outside the checkout.
#
# Layers it covers:
#   - Repo conventions: AI-declaration header, PR scope-gate self-test,
#     local issue-tracker layout (.scratch/ is gitignored, so no CI job can)
#   - GitHub/AppVeyor YAML parse (Bun)
#   - Python backend suite on the shipped interpreter
#   - Node backend suite on the shipped node.exe
#   - Go backend tests + the shipped Windows/386 cross-build
#   - Rust launcher tests, cargo fmt, cargo clippy
#   - C++ pure helpers (JsonUtils gtest, CompositionCursor) via mingw-w64 g++
#
# The C++/TSF text service and the NSIS installer need MSVC and stay in CI
# (docs/agents/verification.md).
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later

set -u

# Discovery would otherwise leave __pycache__ trees in the checkout, ready for a
# later `git add` to sweep into a commit: the product .gitignore does not cover
# them and tests/check_pr_scope.sh fails a branch that carries them. Mirrors
# tests/run_local_tests.sh.
export PYTHONDONTWRITEBYTECODE=1

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
TOOLS="$ROOT/.tools"
RUN_DIR="$TOOLS/.run"

failures=0
passed=0

# A run takes eleven minutes: a file edited while it runs leaves every PASS
# above predating that edit, invisibly. Snapshot the tree the run speaks for so
# the tally can say which layers the reader may no longer trust.
HEAD_BEFORE=$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo unknown)
STATUS_BEFORE=$(git -C "$ROOT" status --porcelain 2>/dev/null || echo unknown)

# What a layer just cost, so the run itself is the source for the cost figures
# a doc would otherwise carry by hand (docs/agents/verification.md).
step_start=$SECONDS

pass() { printf 'PASS  %s (%ds)\n' "$1" "$((SECONDS - step_start))"; passed=$((passed + 1)); }
fail() { printf 'FAIL  %s (%ds)\n' "$1" "$((SECONDS - step_start))"; failures=$((failures + 1)); }

mkdir -p "$RUN_DIR"

# Preflight: the toolchain lives under .tools/ (excluded from git), so a fresh
# clone has to install it before this script can run.
missing=()
for tool in "$TOOLS/go/bin/go.exe" "$TOOLS/node/node.exe" "$TOOLS/bun/bun.exe" \
	"$TOOLS/cargo/bin/cargo.exe" "$TOOLS/mingw64/bin/g++.exe"; do
	[ -x "$tool" ] || missing+=("$tool")
done
if [ ${#missing[@]} -gt 0 ]; then
	printf 'MISSING toolchain files:\n'
	printf '  %s\n' "${missing[@]}"
	printf 'Run: bash tests/install_windows_toolchain.sh\n'
	exit 1
fi

# Native Windows programs need a Windows-style PATH: this shell keeps PATH
# colon-separated, which CreateProcess cannot search. Each step runs through a
# generated .bat that sets the tool directories in Windows form.
# A step's environment: the tool directories plus the per-user homes the
# toolchains look for (cargo is a rustup proxy and needs RUSTUP_HOME).
# CARGO_TARGET_DIR is shared so every worktree reuses one dependency cache.
write_step() {
	local bat="$RUN_DIR/step.bat"
	local win_tools win_root
	win_tools=$(cygpath -w "$TOOLS")
	win_root=$(cygpath -w "$ROOT")
	{
		printf '%s\r\n' '@echo off'
		printf '%s\r\n' "set \"PATH=$win_tools\\mingw64\\bin;$win_tools\\go\\bin;$win_tools\\bun;$win_tools\\node;$win_tools\\cargo\\bin;$win_tools\\bin;%PATH%\""
		printf '%s\r\n' "set \"GOROOT=$win_tools\\go\""
		printf '%s\r\n' "set \"GOPATH=$win_tools\\gopath\""
		printf '%s\r\n' "set \"CARGO_HOME=$win_tools\\cargo\""
		printf '%s\r\n' "set \"RUSTUP_HOME=$win_tools\\rustup\""
		printf '%s\r\n' "set \"CARGO_TARGET_DIR=$win_tools\\cargo-target\""
		printf '%s\r\n' "cd /d \"$win_root\""
		printf '%s\r\n' "$*"
	} >"$bat"
}

run_native() {
	local label="$1"
	shift
	step_start=$SECONDS
	write_step "$*"
	if "$RUN_DIR/step.bat" >"$RUN_DIR/step.log" 2>&1; then
		pass "$label"
	else
		fail "$label"
		tail -n 30 "$RUN_DIR/step.log" | sed 's/^/      /'
		cp "$RUN_DIR/step.log" "$RUN_DIR/fail-${label//[^A-Za-z0-9]/-}.log"
	fi
}

# A gate that answers 125 when the branch it would judge does not live here (the
# commit-claims gate on an integration branch) is a skip, not a failure — same
# reasoning as the tracker layer below.
run_or_skip() {
	local label="$1"
	shift
	step_start=$SECONDS
	write_step "$*"
	if "$RUN_DIR/step.bat" >"$RUN_DIR/step.log" 2>&1; then
		pass "$label"
	elif [ $? -eq 125 ]; then
		pass "$label (not applicable)"
	else
		fail "$label"
		tail -n 30 "$RUN_DIR/step.log" | sed 's/^/      /'
		cp "$RUN_DIR/step.log" "$RUN_DIR/fail-${label//[^A-Za-z0-9]/-}.log"
	fi
}

# Same, but keeps the step output visible (for failing or noisy steps).
run_native_verbose() {
	local label="$1"
	shift
	step_start=$SECONDS
	write_step "$*"
	local log rc
	log=$("$RUN_DIR/step.bat" 2>&1)
	rc=$?
	if [ $rc -eq 0 ]; then
		pass "$label"
		printf '%s\n' "$log" | tail -n 12 | sed 's/^/      /'
	else
		fail "$label"
		# A noisy step is the one whose failure matters most: show enough of it to
		# read the traceback, and keep the rest beside the run.
		printf '%s\n' "$log" | tail -n 40 | sed 's/^/      /'
		printf '%s\n' "$log" >"$RUN_DIR/fail-${label//[^A-Za-z0-9]/-}.log"
	fi
}

printf 'PIME local verification (root: %s)\n' "$ROOT"

# --- YAML -----------------------------------------------------------------
yaml_files=$(find .github -type f \( -name '*.yml' -o -name '*.yaml' \) -print; printf '%s\n' appveyor.yml)
yaml_args=""
for f in $yaml_files; do
	yaml_args="$yaml_args \"$(cygpath -w "$f")\""
done
run_native 'GitHub YAML parses' \
	"bun.exe \"$(cygpath -w "$ROOT/tests/check_yaml.ts")\"$yaml_args"

# --- Authorship -------------------------------------------------------------
# check_ai_declarations.sh otherwise runs only under the Linux gate, so a
# missing header on a branch added here shows up first at the wrong end of
# the chain. The check is diff-scoped against origin/master, so it is a
# no-op (exit 0) on the mirror branch and bites on win/* branches.
run_native 'Added files carry an AI declaration' \
	'bash.exe tests/check_ai_declarations.sh'

# The gate decides what reaches an upstream PR, so its exit-code contract is
# pinned by a self-test on both boxes, not only under the Linux gate.
run_native 'PR scope gate self-test' \
	'bash.exe tests/check_pr_scope_test.sh'

# Same contract pinning for the declaration gate: its staged mode is what the
# pre-commit hook trusts to judge a commit still in the index.
run_native 'AI declaration self-test' \
	'bash.exe tests/check_ai_declarations_test.sh'

# The worktree driver decides what code a PR review's test run exercises,
# so its discovery form and abort contract get the same pinning.
run_native 'Worktree test driver self-test' \
	'bash.exe tests/run_worktree_tests_test.sh'

# The tracker is git-excluded, so a .scratch/ citation committed into shipped
# or executed code is a dead link on every fresh clone; the gate scans the
# code tree and its self-test pins the allowlist boundary.
run_native 'Tracked code cites no .scratch/' \
	'bash.exe tests/check_scratch_refs.sh'
run_native 'Scratch-ref gate self-test' \
	'bash.exe tests/check_scratch_refs_test.sh'

# The PR body is pasted by hand on the box that delivers the PR — this one —
# and .scratch/ is gitignored, so no CI job can ever read the draft: the
# declaration gate has to run here, pinned by its own self-test.
run_native 'PR bodies carry the AI declaration' \
	'bash.exe tests/check_pr_bodies.sh'
run_native 'PR body gate self-test' \
	'bash.exe tests/check_pr_bodies_test.sh'

# A product PR branch carries no tests/, so a commit message copied from the
# integration branch by `git commit -C` ends up promising a test the reviewer
# cannot find. The gate judges the branch under delivery, so here it runs against
# the current branch and skips on the integration branch; its contract is pinned
# by the self-test either way.
run_or_skip 'PR commit messages claim only their own diff' \
	'bash.exe tests/check_pr_commit_claims.sh'
run_native 'Commit-claims gate self-test' \
	'bash.exe tests/check_pr_commit_claims_test.sh'

# The same carried-over commit can also lose the #996 declaration outright:
# PR #1010 shipped two commits whose messages carry none and no gate noticed.
# This gate judges every commit on a product-bound branch, so here it runs
# against the current branch and skips on the integration branch; its
# contract is pinned by the self-test either way.
run_or_skip 'PR commit messages carry the AI declaration' \
	'bash.exe tests/check_pr_commit_declarations.sh'
run_native 'Commit-declaration gate self-test' \
	'bash.exe tests/check_pr_commit_declarations_test.sh'

# A .sh committed from a core.filemode=false checkout lands 100644, and
# run_local_tests.sh's step() executes scripts directly: the fork's
# linux-checks answers such a step with exit 126. verify_windows.sh calls
# every script through bash.exe, so this is the only layer that sees the
# tree is missing the bit.
run_native 'Shell scripts carry the exec bit' \
	'bash.exe tests/check_sh_exec_bits.sh'
run_native 'Exec-bit gate self-test' \
	'bash.exe tests/check_sh_exec_bits_test.sh'

# Pushing a ref that still carries the unhardened workflows mails the fork owner
# one failure per push; the gate needs a ref to read, so the gate itself runs at
# delivery time (docs/agents/upstream-pr.md) and only its contract runs here.
run_native 'Fork CI noise gate self-test' \
	'bash.exe tests/check_fork_ci_noise_test.sh'

# Which `local/*` branch is the integration ref is a fact two sessions have got
# wrong by remembering a name; the report names the candidates every run and never
# fails (docs/agents/shared-checkout.md).
run_native 'Integration ref candidates' \
	'bash.exe tests/check_integration_ref.sh'

# The tracker lives in .scratch/, which is gitignored, so no CI job can ever see
# it: the layout check belongs on the box that holds the tickets. Exit 125 means
# "no .scratch here", which is not a failure.
step_start=$SECONDS
write_step 'bash.exe tests/check_tracker_layout.sh'
if "$RUN_DIR/step.bat" >"$RUN_DIR/step.log" 2>&1; then
	pass 'Local issue tracker layout'
elif [ $? -eq 125 ]; then
	pass 'Local issue tracker layout (no .scratch)'
else
	fail 'Local issue tracker layout'
	tail -n 15 "$RUN_DIR/step.log" | sed 's/^/      /'
fi

# --- Python ---------------------------------------------------------------
run_native_verbose 'Python backend tests (bundled python.exe)' \
	'python\python3\python.exe -m unittest discover -s tests -p test_*.py'

# --- Node -----------------------------------------------------------------
run_native 'Node backend tests (bundled node.exe)' \
	'node\node.exe --test node\tests\nimeServer.test.js'
run_native 'Node backend tests (server)' \
	'node\node.exe node\test\server.test.js'
run_native 'Node backend tests (loadServices)' \
	'node\node.exe node\test\loadServices.test.js'

# --- Go -------------------------------------------------------------------
# -count=1: a cached `ok` is not evidence — the rime runtime tests once sat
# cached-green while a fresh run failed them on this arm64 box, because the
# bundled x64 rime.dll cannot load into an arm64 process. APPDATA is cleared
# so those tests reach their own skip deterministically instead of riding on
# whatever %APPDATA%\Rime an installed PIME left behind; the real rime pass is
# the GOARCH=amd64 brise run at PR-delivery time (docs/agents/verification.md).
run_native 'Go backend tests' \
	'cd go-backend && set "APPDATA=" && go.exe test -count=1 ./...'
run_native 'Go backend Windows/386 build' \
	'cd go-backend && set "CGO_ENABLED=0" && set "GOOS=windows" && set "GOARCH=386" && go.exe build ./...'

# --- Rust -----------------------------------------------------------------
# The repo pins i686-pc-windows-msvc (see PIMELauncher/.cargo/config.toml);
# MSVC needs Visual Studio, so the local run uses the GNU toolchain instead.
# One test thread: the integration tests share the machine's pipe and backend
# slots, and parallel runs starve each other on slow or emulated hosts.
run_native 'Rust launcher tests' \
	'cd PIMELauncher && cargo.exe test --target x86_64-pc-windows-gnu -- --test-threads=1'
run_native 'Rust cargo fmt --check' 'cd PIMELauncher && cargo.exe fmt --check'
run_native 'Rust cargo clippy' \
	'cd PIMELauncher && cargo.exe clippy --target x86_64-pc-windows-gnu --all-targets -- -D warnings'

# --- C++ pure helpers -----------------------------------------------------
gtest='libIME2/lib/googletest-release-1.10.0/googletest'
run_native 'C++ JsonUtils tests (gtest, mingw g++)' \
	"g++.exe -std=c++17 -O1 -pthread -I PIMETextService -I json/single_include -I $gtest/include -I $gtest tests\\json_utils_test.cpp $gtest/src/gtest-all.cc $gtest/src/gtest_main.cc -o .tools\\json_utils_test.exe && .tools\\json_utils_test.exe"
run_native 'C++ CompositionCursor test (mingw g++)' \
	'g++.exe -std=c++17 -O1 -static -I PIMETextService tests\\composition_cursor_test.cpp -o .tools\\composition_cursor_test.exe && .tools\\composition_cursor_test.exe'

# Trust anchor: if HEAD or the worktree moved while the layers ran, the PASS
# lines speak for the old tree — say so instead of letting a green tally hide
# the drift; the reader reruns the affected layers on the final bytes.
HEAD_NOW=$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo unknown)
STATUS_NOW=$(git -C "$ROOT" status --porcelain 2>/dev/null || echo unknown)
if [ "$HEAD_NOW" != "$HEAD_BEFORE" ]; then
	printf 'WARN  HEAD moved during the run (%s -> %s): no layer above validated the new commits\n' "${HEAD_BEFORE:0:7}" "${HEAD_NOW:0:7}"
fi
if [ "$STATUS_NOW" != "$STATUS_BEFORE" ]; then
	printf '%s\n' "$STATUS_BEFORE" >"$RUN_DIR/status.before"
	printf '%s\n' "$STATUS_NOW" >"$RUN_DIR/status.now"
	printf 'WARN  worktree changed during the run; these paths may predate your edits:\n'
	comm -3 "$RUN_DIR/status.before" "$RUN_DIR/status.now" | sed 's/^/      /'
	rm -f "$RUN_DIR/status.before" "$RUN_DIR/status.now"
fi

# A failing layer's own output is what has to be read; deleting it here sends the
# reader into a rerun of a three-minute step.
if [ "$failures" -eq 0 ]; then
	rm -rf "$RUN_DIR"
else
	printf 'step logs kept for the failing layers: %s\n' "$RUN_DIR"
fi

printf '\n%d passed, %d failed\n' "$passed" "$failures"
[ "$failures" -eq 0 ]

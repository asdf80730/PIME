#!/usr/bin/env bash
# Regression test for tests/check_pr_scope.sh: the gate decides whether a
# sediment branch reaches an upstream PR, so its exit codes are contract.
# Each assertion drives the gate from a throwaway worktree and compares the
# documented code — the tracked-path FAIL is the case a merge-base test cannot
# catch (fork mirror at master's SHA), so it is pinned here, not by ancestry.
#
# Usage: run from any checkout; designed for the integration branch, where
# docs/agents and GLOSSARY.md are tracked and the FAIL case bites. An
# assertion whose precondition is absent skips instead of failing.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later

set -u

root=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  PR scope self-test (not inside a git checkout)\n'
    exit 125
}
gate=$root/tests/check_pr_scope.sh
[ -f "$gate" ] || {
    printf 'SKIP  PR scope self-test (gate absent on this branch)\n'
    exit 125
}

# Not a bare /tmp: MSYS child shells default TMP/TEMP to /tmp, and native
# git.exe then maps a /tmp argument to C:\tmp while bash sees %TEMP% — the
# worktree lands where the shell cannot find it. A real WinTEMP template
# yields a C:/... path both bash and git.exe resolve identically.
if command -v cygpath >/dev/null 2>&1 && [ -n "${USERPROFILE:-}" ]; then
    tmpbase=$(cygpath -w "$USERPROFILE/AppData/Local/Temp")
else
    tmpbase="${TMPDIR:-/tmp}"
fi
tmp=$(mktemp -d "$tmpbase/pime-pr-scope-selftest.XXXXXX")
branch_bad=selftest/scope-dirty.$$
branch_ok=selftest/scope-clean.$$
branch_pyc=selftest/scope-pyc.$$
work_bad=$tmp/bad
work_detached=$tmp/detached
work_ok=$tmp/ok
work_pyc=$tmp/pyc

cleanup() {
    git worktree remove --force "$work_bad" 2>/dev/null
    git worktree remove --force "$work_detached" 2>/dev/null
    git worktree remove --force "$work_ok" 2>/dev/null
    git worktree remove --force "$work_pyc" 2>/dev/null
    git worktree prune 2>/dev/null
    git branch -D "$branch_bad" "$branch_ok" "$branch_pyc" 2>/dev/null
    rm -rf "$tmp"
}
trap cleanup EXIT

failures=0
skipped=0

EXPECT_ENV=()

# expect <want-code> <name> <workdir> [gate-args...]
# The gate must see the worktree's index, so it runs with cwd inside it;
# GITHUB_HEAD_REF would silently replace the branch argument in CI, and
# GITHUB_BASE_REF would make every assertion a base-ref skip there.
expect() {
    local want=$1 name=$2 dir=$3
    shift 3
    local out got=0
    out=$(cd "$dir" && env -u GITHUB_HEAD_REF -u GITHUB_BASE_REF ${EXPECT_ENV[@]+"${EXPECT_ENV[@]}"} bash "$gate" "$@" 2>&1) || got=$?
    if [ "$got" -eq "$want" ]; then
        printf 'PASS  %s (exit %s)\n' "$name" "$want"
    else
        printf 'FAIL  %s: want exit %s, got %s\n%s\n' "$name" "$want" "$got" "$out"
        failures=$((failures + 1))
    fi
}

# 1. Integration and local record branch names skip, whatever the checkout looks like.
expect 125 'integration branch name skips' "$root" local/linux-master
expect 125 'local record branch skips' "$root" local/stroke-parked

# 2. Detached HEAD with no argument is not applicable, not a silent pass.
git worktree add --detach "$work_detached" HEAD >/dev/null 2>&1
# git can return 0 while the checkout lands where this shell cannot see it
# (the Windows /tmp alias again), so the directory itself is the proof.
if [ ! -d "$work_detached" ]; then
    printf 'FAIL  could not create throwaway worktree at %s\n' "$work_detached"
    exit 1
fi
expect 125 'detached HEAD without argument skips' "$work_detached"

# 3. A branch cut from the integration HEAD FAILs on tracked paths even when
#    nothing else could catch it. Every remote is neutralized through
#    GIT_CONFIG_* (command-line level, highest precedence): with the product
#    master unresolvable, only the tracked-path check can bite — the exact
#    shape of a Windows box with no EasyIME/PIME remote. Only asserted where
#    integration-only paths are actually tracked (the integration branch).
if [ -n "$(git ls-files -- docs/agents GLOSSARY.md .scratch | head -n 1)" ]; then
    git worktree add -B "$branch_bad" "$work_bad" HEAD >/dev/null 2>&1 || {
        printf 'FAIL  could not create dirty throwaway worktree\n'
        exit 1
    }
    n=0
    EXPECT_ENV=()
    for r in $(git remote); do
        EXPECT_ENV+=("GIT_CONFIG_KEY_$n=remote.$r.url"
                     "GIT_CONFIG_VALUE_$n=https://example.invalid/noremote.git")
        n=$((n + 1))
    done
    [ "$n" -gt 0 ] && EXPECT_ENV+=("GIT_CONFIG_COUNT=$n")
    expect 1 'integration-sourced branch fails tracked-path check' "$work_bad"
    EXPECT_ENV=()
else
    printf 'SKIP  tracked-path check (checkout tracks no integration-only files)\n'
    skipped=$((skipped + 1))
fi

# 4. A branch sitting on the product master PASSes and the tracked-path check
#    stays quiet on a clean tree. Needs the same EasyIME/PIME remote the gate
#    itself resolves, so it skips in lockstep with the gate.
base_ref=
for remote in $(git remote); do
    case "$(git config --get "remote.$remote.url" || true)" in
        *EasyIME/PIME*) base_ref="$remote/master"; break ;;
    esac
done
if [ -n "$base_ref" ] && git rev-parse --verify --quiet "$base_ref" >/dev/null; then
    git worktree add -B "$branch_ok" "$work_ok" "$base_ref" >/dev/null 2>&1
    if [ -d "$work_ok" ]; then
        expect 0 'clean branch on product master passes' "$work_ok" "$branch_ok"
    else
        printf 'SKIP  clean-branch PASS (worktree at %s unavailable)\n' "$base_ref"
        skipped=$((skipped + 1))
    fi
else
    printf 'SKIP  clean-branch PASS (no %s; same skip the gate takes)\n' \
        "${base_ref:-EasyIME/PIME remote}"
    skipped=$((skipped + 1))
fi

# 5. Bytecode caches in the diff FAIL: the product .gitignore carries no
#    __pycache__ entry until EasyIME/PIME#1015 lands, so a directory-wide
#    git add from a product worktree sweeps them in. -f defeats any local
#    ignore, mirroring what an unignored worktree commits.
if [ -n "$base_ref" ] && git rev-parse --verify --quiet "$base_ref" >/dev/null; then
    git worktree add -B "$branch_pyc" "$work_pyc" "$base_ref" >/dev/null 2>&1
    if [ -d "$work_pyc" ]; then
        mkdir -p "$work_pyc/python/cinbase/__pycache__"
        printf 'x' > "$work_pyc/python/cinbase/__pycache__/stale.cpython-315.pyc"
        git -C "$work_pyc" add -f python/cinbase/__pycache__/stale.cpython-315.pyc >/dev/null 2>&1
        git -C "$work_pyc" commit -qm 'selftest: bytecode cache in diff' >/dev/null 2>&1
        expect 1 'branch carrying bytecode fails the gate' "$work_pyc" "$branch_pyc"
    else
        printf 'SKIP  bytecode FAIL (worktree at %s unavailable)\n' "$base_ref"
        skipped=$((skipped + 1))
    fi
fi

printf '%d failed, %d skipped\n' "$failures" "$skipped"
[ "$failures" -eq 0 ]

#!/usr/bin/env bash
# Regression test for tests/check_pr_scope.sh: the gate decides whether a
# sediment branch reaches an upstream PR, so its exit codes are contract.
# Each assertion drives the gate from a throwaway worktree and compares the
# documented code — the tracked-path FAIL is the case a merge-base test cannot
# catch (fork mirror at master's SHA), so it is pinned here, not by ancestry.
#
# Usage: run from any checkout; designed for the integration branch, where
# docs/agents and GLOSSARY.md are tracked and the FAIL case bites. An
# assertion whose precondition is absent skips instead of failing.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later

set -u

. "${BASH_SOURCE[0]%/*}/gate_lib.sh"

gate_root 'PR scope self-test' || exit $?
gate=$ROOT/tests/check_pr_scope.sh
[ -f "$gate" ] || {
    printf 'SKIP  PR scope self-test (gate absent on this branch)\n'
    exit 125
}

gate_sandbox pime-pr-scope-selftest
branch_bad=selftest/scope-dirty.$$
branch_ok=selftest/scope-clean.$$
branch_pyc=selftest/scope-pyc.$$
work_bad=$tmp/bad
work_detached=$tmp/detached
work_ok=$tmp/ok
work_pyc=$tmp/pyc
branch_sym=selftest/scope-sym.$$
work_sym=$tmp/sym
branch_state=selftest/scope-state.$$
work_state=$tmp/state
branch_pr=selftest/scope-pr.$$
work_pr=$tmp/pr
branch_go=selftest/scope-go.$$
work_go=$tmp/go
branch_go2=selftest/scope-go2.$$
work_go2=$tmp/go2

# The trap runs after the summary line, so every command here is silenced: a
# tail of the run then ends on `N failed, M skipped` instead of git bookkeeping.
cleanup() {
    git worktree remove --force "$work_bad" >/dev/null 2>&1
    git worktree remove --force "$work_detached" >/dev/null 2>&1
    git worktree remove --force "$work_ok" >/dev/null 2>&1
    git worktree remove --force "$work_pyc" >/dev/null 2>&1
    git worktree remove --force "$work_sym" >/dev/null 2>&1
    git worktree remove --force "$work_state" >/dev/null 2>&1
    git worktree remove --force "$work_pr" >/dev/null 2>&1
    git worktree remove --force "$work_go" >/dev/null 2>&1
    git worktree remove --force "$work_go2" >/dev/null 2>&1
    git worktree prune >/dev/null 2>&1
    git branch -D "$branch_bad" "$branch_ok" "$branch_pyc" "$branch_sym" \
        "$branch_state" "$branch_pr" "$branch_go" "$branch_go2" >/dev/null 2>&1
    rm -rf "$tmp"
}
trap cleanup EXIT

failures=0
skipped=0

EXPECT_ENV=()

# expect <want-code> <name> <workdir> [gate-args...]
# The gate must see the worktree's index, so it runs with cwd inside it;
# GITHUB_HEAD_REF would silently replace the branch argument in CI, and
# GITHUB_BASE_REF would make every assertion a base-ref skip there.
expect() {
    local want=$1 name=$2 dir=$3
    shift 3
    local out got=0
    out=$(cd "$dir" && env -u GITHUB_HEAD_REF -u GITHUB_BASE_REF ${EXPECT_ENV[@]+"${EXPECT_ENV[@]}"} bash "$gate" "$@" 2>&1) || got=$?
    if [ "$got" -eq "$want" ]; then
        printf 'PASS  %s (exit %s)\n' "$name" "$want"
    else
        printf 'FAIL  %s: want exit %s, got %s\n%s\n' "$name" "$want" "$got" "$out"
        failures=$((failures + 1))
    fi
}

# 1. Integration and local record branch names skip, whatever the checkout looks like.
expect 125 'integration branch name skips' "$ROOT" local/linux-master
expect 125 'local record branch skips' "$ROOT" local/stroke-parked

# 1b. The same names as a pull-request base: harness work is the base's own
# content there, so the scope rules cannot judge it. The retired mirror keeps its
# entry because PRs delivered before the merge still carry it as their base.
EXPECT_ENV=(GITHUB_BASE_REF=local/stroke-parked)
expect 125 'base on the integration ref skips' "$ROOT" pr/scope-sample
EXPECT_ENV=(GITHUB_BASE_REF=local/linux-master)
expect 125 'base on the retired mirror skips' "$ROOT" pr/scope-sample
EXPECT_ENV=()

# 2. Detached HEAD with no argument is not applicable, not a silent pass.
git worktree add --detach "$work_detached" HEAD >/dev/null 2>&1
# git can return 0 while the checkout lands where this shell cannot see it
# (the Windows /tmp alias again), so the directory itself is the proof.
if [ ! -d "$work_detached" ]; then
    printf 'FAIL  could not create throwaway worktree at %s\n' "$work_detached"
    exit 1
fi
expect 125 'detached HEAD without argument skips' "$work_detached"

# 3. A branch cut from the integration HEAD FAILs on tracked paths even when
#    nothing else could catch it. Every remote is neutralized through
#    GIT_CONFIG_* (command-line level, highest precedence): with the product
#    master unresolvable, only the tracked-path check can bite — the exact
#    shape of a Windows box with no EasyIME/PIME remote. Only asserted where
#    integration-only paths are actually tracked (the integration branch).
if [ -n "$(git ls-files -- docs/agents GLOSSARY.md .scratch | head -n 1)" ]; then
    git worktree add -B "$branch_bad" "$work_bad" HEAD >/dev/null 2>&1 || {
        printf 'FAIL  could not create dirty throwaway worktree\n'
        exit 1
    }
    n=0
    EXPECT_ENV=()
    for r in $(git remote); do
        EXPECT_ENV+=("GIT_CONFIG_KEY_$n=remote.$r.url"
                     "GIT_CONFIG_VALUE_$n=https://example.invalid/noremote.git")
        n=$((n + 1))
    done
    [ "$n" -gt 0 ] && EXPECT_ENV+=("GIT_CONFIG_COUNT=$n")
    expect 1 'integration-sourced branch fails tracked-path check' "$work_bad"
    EXPECT_ENV=()
else
    printf 'SKIP  tracked-path check (checkout tracks no integration-only files)\n'
    skipped=$((skipped + 1))
fi

# 4. A branch sitting on the product master PASSes and the tracked-path check
#    stays quiet on a clean tree. Needs the same EasyIME/PIME remote the gate
#    itself resolves, so it skips in lockstep with the gate.
base_ref=
for remote in $(git remote); do
    case "$(git config --get "remote.$remote.url" || true)" in
        *EasyIME/PIME*) base_ref="$remote/master"; break ;;
    esac
done
if [ -n "$base_ref" ] && git rev-parse --verify --quiet "$base_ref" >/dev/null; then
    git worktree add -B "$branch_ok" "$work_ok" "$base_ref" >/dev/null 2>&1
    if [ -d "$work_ok" ]; then
        expect 0 'clean branch on product master passes' "$work_ok" "$branch_ok"
    else
        printf 'SKIP  clean-branch PASS (worktree at %s unavailable)\n' "$base_ref"
        skipped=$((skipped + 1))
    fi
else
    printf 'SKIP  clean-branch PASS (no %s; same skip the gate takes)\n' \
        "${base_ref:-EasyIME/PIME remote}"
    skipped=$((skipped + 1))
fi

# 5. Bytecode caches in the diff FAIL: the product .gitignore carries no
#    __pycache__ entry until EasyIME/PIME#1015 lands, so a directory-wide
#    git add from a product worktree sweeps them in. -f defeats any local
#    ignore, mirroring what an unignored worktree commits.
if [ -n "$base_ref" ] && git rev-parse --verify --quiet "$base_ref" >/dev/null; then
    git worktree add -B "$branch_pyc" "$work_pyc" "$base_ref" >/dev/null 2>&1
    if [ -d "$work_pyc" ]; then
        mkdir -p "$work_pyc/python/cinbase/__pycache__"
        printf 'x' > "$work_pyc/python/cinbase/__pycache__/stale.cpython-315.pyc"
        git -C "$work_pyc" add -f python/cinbase/__pycache__/stale.cpython-315.pyc >/dev/null 2>&1
        git -C "$work_pyc" commit -qm 'selftest: bytecode cache in diff' >/dev/null 2>&1
        expect 1 'branch carrying bytecode fails the gate' "$work_pyc" "$branch_pyc"
    else
        printf 'SKIP  bytecode FAIL (worktree at %s unavailable)\n' "$base_ref"
        skipped=$((skipped + 1))
    fi
fi

# 6/7. The pick symmetry: a `cherry-pick -n` answered with the *ours* side keeps
#      the paths the twin dropped. Two commits with one subject and the same
#      path set pass; the same pair with one path missing fails. Product paths
#      only, so the harness exclusion cannot mask the gap.
if [ -n "$base_ref" ] && git rev-parse --verify --quiet "$base_ref" >/dev/null; then
    git worktree add -B "$branch_sym" "$work_sym" "$base_ref" >/dev/null 2>&1
    if [ -d "$work_sym" ]; then
        printf 'a\n' >"$work_sym/selftest-sym-a.txt"
        printf 'b\n' >"$work_sym/selftest-sym-b.txt"
        git -C "$work_sym" add selftest-sym-a.txt selftest-sym-b.txt >/dev/null 2>&1
        git -C "$work_sym" commit -qm 'selftest: symmetry twin carries two paths' >/dev/null 2>&1
        expect 0 'picked commit matching its twin passes' "$work_sym" "$branch_sym"

        printf 'b2\n' >"$work_sym/selftest-sym-b.txt"
        git -C "$work_sym" add selftest-sym-b.txt >/dev/null 2>&1
        git -C "$work_sym" commit -qm 'selftest: symmetry twin carries two paths' >/dev/null 2>&1
        expect 1 'picked commit that dropped a path fails' "$work_sym" "$branch_sym"
    else
        printf 'SKIP  pick symmetry (worktree at %s unavailable)\n' "$base_ref"
        skipped=$((skipped + 1))
    fi
fi

# 8. A twin written against an integration-only state is not a dropped pick:
#    the twin branch first carries a file the product base never had, so the
#    twin's own parent already differs there. The same-subject PR commit that
#    mirrors only the two base-side paths therefore passes, while the case-7
#    pair above still fails — the two together pin the per-path filter.
if [ -n "$base_ref" ] && git rev-parse --verify --quiet "$base_ref" >/dev/null; then
    git worktree add -B "$branch_state" "$work_state" "$base_ref" >/dev/null 2>&1
    git worktree add -B "$branch_pr" "$work_pr" "$base_ref" >/dev/null 2>&1
    if [ -d "$work_state" ] && [ -d "$work_pr" ]; then
        printf 'i\n' >"$work_state/selftest-sym-int.txt"
        git -C "$work_state" add selftest-sym-int.txt >/dev/null 2>&1
        git -C "$work_state" commit -qm 'selftest: integration-only state' >/dev/null 2>&1
        printf 'a3\n' >"$work_state/selftest-sym-a.txt"
        printf 'b3\n' >"$work_state/selftest-sym-b.txt"
        printf 'i3\n' >"$work_state/selftest-sym-int.txt"
        git -C "$work_state" add selftest-sym-a.txt selftest-sym-b.txt \
            selftest-sym-int.txt >/dev/null 2>&1
        git -C "$work_state" commit -qm 'selftest: symmetry twin carries two paths' >/dev/null 2>&1

        printf 'a3\n' >"$work_pr/selftest-sym-a.txt"
        printf 'b3\n' >"$work_pr/selftest-sym-b.txt"
        git -C "$work_pr" add selftest-sym-a.txt selftest-sym-b.txt >/dev/null 2>&1
        git -C "$work_pr" commit -qm 'selftest: symmetry twin carries two paths' >/dev/null 2>&1
        expect 0 'twin written on a later state does not bite' "$work_pr" "$branch_pr"
    else
        printf 'SKIP  later-state twin (worktree at %s unavailable)\n' "$base_ref"
        skipped=$((skipped + 1))
    fi
fi

# 9. The runner-local test files are not part of the product comparison: the
#    Go and Node suites live on the integration ref, so a twin that adds them
#    beside one product path still matches a branch that carries only that
#    path. Without the two extra prefixes the gap is the pair of test files and
#    this assertion goes red.
if [ -n "$base_ref" ] && git rev-parse --verify --quiet "$base_ref" >/dev/null; then
    git worktree add -B "$branch_go" "$work_go" "$base_ref" >/dev/null 2>&1
    git worktree add -B "$branch_go2" "$work_go2" "$base_ref" >/dev/null 2>&1
    if [ -d "$work_go" ] && [ -d "$work_go2" ]; then
        printf 'a\n' >"$work_go/selftest-sym2-a.txt"
        printf 'package main\n' >"$work_go/go-backend/server_test.go"
        mkdir -p "$work_go/node"
        printf '// test\n' >"$work_go/node/x.test.js"
        git -C "$work_go" add selftest-sym2-a.txt go-backend/server_test.go \
            node/x.test.js >/dev/null 2>&1
        git -C "$work_go" commit -qm 'selftest: twin adds the runner-local suites' >/dev/null 2>&1

        printf 'a\n' >"$work_go2/selftest-sym2-a.txt"
        git -C "$work_go2" add selftest-sym2-a.txt >/dev/null 2>&1
        git -C "$work_go2" commit -qm 'selftest: twin adds the runner-local suites' >/dev/null 2>&1
        expect 0 'runner-local test files stay out of the comparison' "$work_go2" "$branch_go2"
    else
        printf 'SKIP  runner-local suites (worktree at %s unavailable)\n' "$base_ref"
        skipped=$((skipped + 1))
    fi
fi

printf '%d failed, %d skipped\n' "$failures" "$skipped"
[ "$failures" -eq 0 ]
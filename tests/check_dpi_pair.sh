#!/usr/bin/env bash
# The per-monitor DPI helper exists twice on this branch: the superseded pair
# `PIMETextService/DpiUtils.h` + `tests/dpi_helper_test.cpp`, and the form
# upstream PR #962 lands as `getWindowDpi` inside `PIMETextService.cpp`. Only
# one of the two is current, and both gates keep passing either way: the C++
# step builds whichever test file is present, so an orphaned header survives a
# merge unnoticed. This check pins which side is live.
#
# Rule: the presence of `getWindowDpi` in `PIMETextService/PIMETextService.cpp`
# is the merged side; when it is there, the pair MUST be absent, and while it
# is not, the pair MUST both be present, since both gates compile the helper
# through that test file.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later
#
# Exit codes: 0 the pair matches the merged side, 1 it does not,
# 125 not applicable (no git checkout, or no PIMETextService tree to read).

set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  DPI helper pair (not inside a git checkout)\n'
    exit 125
}
cd "$ROOT" || exit 1

SERVICE="PIMETextService/PIMETextService.cpp"
[ -f "$SERVICE" ] || {
    printf 'SKIP  DPI helper pair (%s absent)\n' "$SERVICE"
    exit 125
}

pair=(PIMETextService/DpiUtils.h tests/dpi_helper_test.cpp)

if grep -q 'getWindowDpi' "$SERVICE"; then
    merged=1
else
    merged=0
fi

bad=0
for path in "${pair[@]}"; do
    if [ "$merged" -eq 1 ] && [ -e "$path" ]; then
        printf 'getWindowDpi is in %s but the superseded file is still carried: %s\n' "$SERVICE" "$path"
        bad=1
    elif [ "$merged" -eq 0 ] && [ ! -e "$path" ]; then
        printf 'the standalone helper is live (no getWindowDpi in %s) but its file is absent: %s\n' \
            "$SERVICE" "$path"
        bad=1
    fi
done

if [ "$bad" -ne 0 ]; then
    printf 'FAIL  DPI helper pair\n'
    exit 1
fi

if [ "$merged" -eq 1 ]; then
    printf 'PASS  DPI helper pair (getWindowDpi in %s, the two stand-in files gone)\n' "$SERVICE"
else
    printf 'PASS  DPI helper pair (stand-in %s + tests/dpi_helper_test.cpp, #962 not merged)\n' \
        "${pair[0]}"
fi
exit 0

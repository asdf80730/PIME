"""Committed cinbase tables stay reproducible from their .cin sources.

The engine reads only the generated JSON and the installer ships only the
json/ directory (installer.nsi excludes cin/), so a .cin edit whose JSON was
never regenerated silently ships the old table. This check regenerates every
committed pair through the very converter the tooling uses — into a temporary
directory, never the working tree — and demands byte equality, plus an exact
json/ inventory so an orphan runtime table cannot linger without a source.

The same committed-pair view also guards the shipped half of an attribution
exhibit: for every ``cin/*.cin`` whose header carries a 顯名聲明, the ``json/``
directory the installer copies must carry the same lines as a
``<stem>.LICENSE.txt`` notice, ``LICENSE.txt`` must name the table, and
``installer.nsi`` must install that inventory. The engine never sees a ``.cin``,
so a header-only exhibit is a licence obligation the user cannot receive.

``PIME_SKIP_TABLE_REGEN=1`` skips the regeneration test only: the pre-commit hook
sets it when no staged path can affect a table, and ``tests/verify_windows.sh``
never sets it, so the full gate always pays for the converter run. The notice
regeneration in ShippedExhibitTests is deliberately outside that flag: it runs the
generator's own ``--emit-license``, which costs milliseconds, not the 35-table
converter pass the flag exists to skip.

Fully generated by omp (DeepSeek V4.1 Flash) without human creative authorship.
Addendum: the shipped-exhibit guard below was generated with AI assistance from
omp (Qwen3.8-Flash-Next) to the architecture directed by the maintainer's
筆畫輸入法 licence brief.
SPDX-License-Identifier: LGPL-2.1-or-later
"""

import contextlib
import importlib.util
import io
import os
import re
import shutil
import tempfile
import unittest

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir))
CINBASE = os.path.join(ROOT, "python", "cinbase")
CIN_DIR = os.path.join(CINBASE, "cin")
JSON_DIR = os.path.join(CINBASE, "json")
CONVERTER = os.path.join(CINBASE, "tools", "cintojson.py")

# Batch-mode charset sorting, mirrored from the converter's main().
SORTED_CIN = {"cnscj.cin", "CnsPhonetic.cin"}

# Generated on the user's machine at install time (installer.nsi converts a
# purchased liu-uni.tab), so no committed source or JSON is expected.
INSTALL_TIME_TABLES = {"liu"}

# The root inventory the installer installs, the installer script that installs
# it, and the stroke-table module that owns the 顯名聲明 wording and the CNS
# fixture. Quoting the exhibit a second time here would hand this guard a copy
# that can drift into agreeing with a broken generator.
LICENSE_TXT = os.path.join(ROOT, "LICENSE.txt")
INSTALLER_NSI = os.path.join(ROOT, "installer", "installer.nsi")
STROKE_TESTS = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "test_cinbase_stroke_table.py")

# The heading 政府資料開放授權條款-第1版 gives its own attachment: a source that
# carries it owes the users of its table the lines underneath.
ATTRIBUTION_MARK = "顯名聲明"


def load_converter():
    """Import cintojson.py by path; it is a tool, not an importable package member."""
    spec = importlib.util.spec_from_file_location("cintojson_for_sync_check", CONVERTER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def cin_stems():
    return sorted(
        name[: -len(".cin")]
        for name in os.listdir(CIN_DIR)
        if name.endswith(".cin")
    )


def load_stroke_tests():
    """The stroke-table test module, by path like the tools: it is a test, not a
    package member, and it is where the exhibit lines and the CNS fixture live."""
    spec = importlib.util.spec_from_file_location("cinbase_stroke_fixtures",
                                                  STROKE_TESTS)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def read_text(path):
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def cin_header(path):
    """The leading ``#`` comments of a .cin: everything above the first directive."""
    lines = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            if not line.startswith("#"):
                break
            lines.append(line.rstrip("\n"))
    return lines


def exhibit_lines(header):
    """The comment block under a header's 顯名聲明 heading, verbatim."""
    for index, line in enumerate(header):
        if ATTRIBUTION_MARK in line:
            block = []
            for following in header[index + 1:]:
                if not following.startswith("# "):
                    break
                block.append(following)
            return block
    return []


def exhibit_tables():
    """[(stem, exhibit lines)] for every committed .cin whose header carries one."""
    owed = []
    for stem in cin_stems():
        lines = exhibit_lines(cin_header(os.path.join(CIN_DIR, stem + ".cin")))
        if lines:
            owed.append((stem, lines))
    return owed


def run_generator(module, argv):
    """Run the generator's CLI in process; return what it printed."""
    printed = io.StringIO()
    with contextlib.redirect_stdout(printed):
        module.main(argv)
    return printed.getvalue()


class CinbaseTableSyncTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.module = load_converter()

    def test_every_source_table_has_a_committed_json(self):
        for stem in cin_stems():
            if stem in INSTALL_TIME_TABLES:
                continue
            with self.subTest(table=stem):
                self.assertTrue(
                    os.path.isfile(os.path.join(JSON_DIR, stem + ".json")),
                    f"cin/{stem}.cin has no committed json/{stem}.json; "
                    "run the converter and commit the pair")

    def test_no_runtime_json_lacks_a_source(self):
        expected = {stem + ".json" for stem in cin_stems()}
        for name in sorted(os.listdir(JSON_DIR)):
            if not name.endswith(".json"):
                continue
            with self.subTest(table=name):
                self.assertIn(
                    name, expected,
                    f"json/{name} ships to users but no cin/ source generates it")

    def test_committed_json_reproduces_the_converter_output(self):
        if os.environ.get("PIME_SKIP_TABLE_REGEN"):
            self.skipTest("PIME_SKIP_TABLE_REGEN is set: no staged path can move a "
                          "table; tests/verify_windows.sh runs this unskipped")
        # getJsonDir() resolves json/ one level under curdir, so anchor
        # curdir one directory below the sandbox: the sandbox's json/ is
        # where converter output lands, never the working tree.
        tmp = tempfile.mkdtemp(prefix="cin-sync-")
        sandbox = os.path.join(tmp, "work")
        os.makedirs(sandbox)
        try:
            for stem in cin_stems():
                if stem in INSTALL_TIME_TABLES:
                    continue
                with self.subTest(table=stem):
                    app = self.module.CinToJson(indent=0)
                    app.curdir = sandbox
                    app.run(stem + ".cin",
                            os.path.join(CIN_DIR, stem + ".cin"),
                            stem + ".cin" in SORTED_CIN)
                    generated = os.path.join(tmp, "json", stem + ".json")
                    committed = os.path.join(JSON_DIR, stem + ".json")
                    self.assertTrue(
                        os.path.isfile(generated),
                        f"converter produced no json for {stem}.cin "
                        "(saveJsonFile swallows I/O errors)")
                    with open(generated, "rb") as handle:
                        fresh = handle.read()
                    with open(committed, "rb") as handle:
                        shipped = handle.read()
                    self.assertEqual(
                        fresh, shipped,
                        f"json/{stem}.json drifted from cin/{stem}.cin; "
                        "rerun the converter and commit the pair")
        finally:
            shutil.rmtree(tmp, ignore_errors=True)


class ShippedExhibitTests(unittest.TestCase):
    """An exhibit a table's source owes must reach the disk a user actually gets.

    ``installer.nsi`` copies cinbase with ``/x "cin"`` and the converter's
    ``saveList`` has no licence key, so the shipped half of an attribution exhibit
    is the ``<stem>.LICENSE.txt`` notice beside the runtime JSON plus the
    ``LICENSE.txt`` inventory the installer installs. Both are generated text, so
    this guard regenerates the notice instead of trusting its bytes.
    """

    @classmethod
    def setUpClass(cls):
        cls.stroke = load_stroke_tests()
        cls.generator = cls.stroke.load_generator()
        cls.notice_suffix = cls.generator.NOTICE_SUFFIX
        cls.owed = exhibit_tables()
        cls.inventory = read_text(LICENSE_TXT)
        cls.installer = read_text(INSTALLER_NSI)

    def test_guard_discovers_a_table_owing_an_exhibit(self):
        """A guard that discovers no exhibit-bearing table guards nothing."""
        self.assertTrue(
            self.owed,
            "no committed .cin header reads as carrying a 顯名聲明, so the "
            "shipped-exhibit guard has stopped covering any table")

    def test_notice_beside_the_json_carries_the_exhibit(self):
        for stem, lines in self.owed:
            with self.subTest(table=stem):
                notice_path = os.path.join(JSON_DIR, stem + self.notice_suffix)
                self.assertTrue(
                    os.path.isfile(notice_path),
                    f"cin/{stem}.cin owes an 顯名聲明 but the json/ directory it "
                    f"ships in has no {stem}{self.notice_suffix}: the exhibit "
                    "reaches no user (generate it with cnsstroke2cin.py "
                    "--emit-license)")
                notice = read_text(notice_path)
                for line in lines:
                    self.assertIn(
                        line + "\n", notice,
                        f"json/{stem}{self.notice_suffix} is missing the "
                        f"顯名聲明 line its own source carries: {line!r}")

    def test_committed_notice_reproduces_the_generator_output(self):
        """Byte equality with ``--emit-license``: the notice is generated, not typed.

        The release quoted inside the exhibit is the stroke module's, because the
        Stroke generator is the only notice-emitting generator in the tree; the
        sandbox keeps the run out of the working tree, like the converter test.
        """
        tmp = tempfile.mkdtemp(prefix="cin-notice-")
        try:
            for stem, _lines in self.owed:
                with self.subTest(table=stem):
                    out_dir = os.path.join(tmp, stem, "cin")
                    os.makedirs(out_dir)
                    printed = run_generator(
                        self.generator,
                        ["-o", os.path.join(out_dir, stem + ".cin"),
                         "--release", self.stroke.RELEASE, "--emit-license"])
                    generated = os.path.join(tmp, stem, "json",
                                             stem + self.notice_suffix)
                    self.assertTrue(
                        os.path.isfile(generated),
                        f"--emit-license wrote no notice for {stem}.cin; it "
                        f"printed {printed!r}")
                    self.assertIn(
                        generated, printed,
                        "--emit-license never said where it wrote the notice")
                    committed = os.path.join(JSON_DIR, stem + self.notice_suffix)
                    with open(generated, "rb") as handle:
                        fresh = handle.read()
                    with open(committed, "rb") as handle:
                        shipped = handle.read()
                    self.assertEqual(
                        fresh, shipped,
                        f"json/{stem}{self.notice_suffix} drifted from what "
                        "cnsstroke2cin.py --emit-license produces; regenerate it, "
                        "never retype the licence text")
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    def test_generation_run_writes_the_notice_beside_the_json(self):
        """``-o`` into cin/ must put the notice in the json/ sibling, or the
        exhibit ships only with the source the installer excludes."""
        tmp = tempfile.mkdtemp(prefix="cin-stroke-run-")
        try:
            out_dir = os.path.join(tmp, "cin")
            os.makedirs(out_dir)
            with self.stroke.StrokeCinFixture(self.stroke.COMMON_CNS,
                                              self.stroke.COMMON_MAPPINGS) as fixture:
                printed = run_generator(
                    self.generator,
                    [fixture.strokes_path, fixture.directory, "-o",
                     os.path.join(out_dir, "CnsStroke.cin"),
                     "--release", self.stroke.RELEASE])
            notice_path = os.path.join(tmp, "json", "CnsStroke" + self.notice_suffix)
            self.assertTrue(
                os.path.isfile(notice_path),
                f"a generation run left no notice in the json/ sibling of its -o "
                f"directory; it printed {printed!r}")
            self.assertIn(notice_path, printed,
                          "a generation run never said where it wrote the notice")
            notice = read_text(notice_path)
            for line in self.stroke.ATTRIBUTION_EXHIBIT:
                self.assertIn(
                    line + "\n", notice,
                    f"the notice a generation run wrote is missing the 顯名聲明 "
                    f"line {line!r}")
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    def test_license_inventory_names_the_table(self):
        for stem, _lines in self.owed:
            with self.subTest(table=stem):
                self.assertIn(
                    f"{stem}.json", self.inventory,
                    f"LICENSE.txt never names {stem}.json, so the inventory that "
                    "tells a user which third-party data shipped with PIME and "
                    "under what licence says nothing about this table")

    def test_installer_ships_the_inventory_and_the_notices(self):
        """``LICENSE.txt`` is installed, and nothing filters ``.txt`` out of it."""
        self.assertRegex(
            self.installer, r'(?im)^\s*File\s+"/?(?:\.\.[\\/])?LICENSE\.txt"',
            'installer/installer.nsi installs no LICENSE.txt, so the inventory '
            "that names each table's exhibit never reaches the user")
        copies = [line.strip() for line in self.installer.splitlines()
                  if line.strip().startswith("File")
                  and re.search(r"python[\\/]cinbase\b", line)]
        self.assertTrue(copies, "no File directive copies python/cinbase at all")
        for line in copies:
            self.assertNotIn(
                "*.txt", line,
                f"{line!r} filters .txt out of the cinbase payload, which "
                f"silently drops the json/*{self.notice_suffix} notices")


if __name__ == "__main__":
    unittest.main()

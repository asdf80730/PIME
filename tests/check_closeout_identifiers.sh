#!/usr/bin/env bash
# A close-out comment is only as good as the identifier it names, so every
# backticked commit SHA and issue/PR number inside a ticket's `## Comments`
# region has to resolve. The 2026-11-12 close-out of ticket 01 quoted the
# identifiers of 13 upstream issues by hand across two docs; a stale or mistyped
# one reads as a fixed reference to the next reader, and `check_line_citations.sh`
# covers only the `file.ext:N` shape, so a dead SHA is the hole it leaves.
#
# Three ranks, because the names age differently and only one of them is a hard
# fact a typo can break:
#   - rank 1, a hex SHA (a token carrying a-f, 7-40 chars): the superproject or
#     one of the `.gitmodules` checkouts has to hold it, and a miss is red. The
#     libchewing pin is legal in its own checkout and nowhere else, so every
#     fetched submodule joins the search. One `git cat-file --batch-check` process
#     per object directory answers the whole set, which is what keeps the step in
#     seconds rather than one `git log` per token.
#   - rank 2, an explicit `#N`: counted, and answered by `gh api` where a `gh` is
#     on PATH; a miss is unchecked, because the small indices those tickets use
#     (`#0`, `#10000`) belong to other trackers.
#   - rank 3, a bare digit string: ambiguous by shape — a 7-digit abbreviation, a
#     tracker number, a date, a GitHub run id — so any one home is enough and a
#     miss is unchecked, with no network read at all.
#
# Only the `## Comments` region is scanned: the header's `Blocked by:` line and the
# checkbox lines belong to `check_tracker_layout.sh`. `.scratch/` is git-excluded,
# so a fresh checkout without the tracker skips (125).
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later
#
# Usage: check_closeout_identifiers.sh [<scratch-dir>] [<search-dir>...]
#   <scratch-dir>  ticket root, default `.scratch`
#   <search-dir>   extra object directories for rank 1, default: this checkout's
#                  `.gitmodules` paths
# Exit codes: 0 every rank-1 SHA resolves, 1 one does not,
# 125 not applicable (no checkout, no scratch dir, no ticket file).

set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  close-out identifiers (not inside a git checkout)\n'
    exit 125
}
cd "$ROOT" || exit 1

scratch=${1:-.scratch}
shift 2>/dev/null || true
if [ ! -d "$scratch" ]; then
    printf 'SKIP  close-out identifiers (no %s in this checkout)\n' "$scratch"
    exit 125
fi

mapfile -t tickets < <(find "$scratch" -mindepth 2 -path '*/issues/*.md' | sort)
if [ "${#tickets[@]}" -eq 0 ]; then
    printf 'SKIP  close-out identifiers (no ticket files under %s)\n' "$scratch"
    exit 125
fi

# Rank-1 homes: the superproject plus every submodule path `.gitmodules` names.
objects=(".")
if [ "$#" -gt 0 ]; then
    objects+=("$@")
elif [ -f .gitmodules ]; then
    while IFS= read -r p; do
        [ -n "$p" ] && objects+=("$p")
    done < <(awk -F' = ' '/^[[:space:]]*path[[:space:]]*=/ { print $2 }' .gitmodules)
fi

have_gh=0
command -v gh >/dev/null 2>&1 && have_gh=1

# One pass over the region: `ticket<TAB>token` per backticked span.
pairs=$(awk '
    FNR == 1 { f = FILENAME }
    /^## Comments/ { inblock[f] = 1; next }
    inblock[f] {
        n = split($0, parts, "`")
        for (i = 2; i <= n; i += 2) if (parts[i] != "") printf "%s\t%s\n", f, parts[i]
    }
' "${tickets[@]}")

# Rank-1 token set, deduped, then one batch-check process per object directory.
# A bare digit string of the same shape joins the batch so an abbreviation such as
# `7676819` is read locally and counted as checked.
declare -A is_sha=() is_num=() held=()
while IFS=$'\t' read -r _ tok; do
    [ -n "${tok:-}" ] || continue
    if [[ "$tok" =~ ^[0-9a-f]*[a-f][0-9a-f]*$ ]] && \
        [[ "$tok" =~ ^[0-9a-f]{7,40}$ ]]; then
        is_sha["$tok"]=1
    elif [[ "$tok" =~ ^[0-9]{7,40}$ ]]; then
        is_num["$tok"]=1
    fi
done <<< "$pairs"

if [ "$((${#is_sha[@]} + ${#is_num[@]}))" -gt 0 ]; then
    mapfile -t sha_list < <(printf '%s\n' "${!is_sha[@]}" "${!is_num[@]}" | sort -u)
    for d in "${objects[@]}"; do
        git -C "$d" rev-parse --git-dir >/dev/null 2>&1 || continue
        # `--batch-check` answers in input order, one line per object, so the token
        # stays the key: an abbreviation would otherwise come back expanded.
        mapfile -t answers < <(printf '%s\n' "${sha_list[@]}" | \
            git -C "$d" cat-file --batch-check)
        for i in "${!sha_list[@]}"; do
            tok=${sha_list[i]}
            line=${answers[i]:-}
            type=${line##* }
            [ -n "$line" ] && [ "$type" != "missing" ] && [ "$type" != "ambiguous" ] && \
                held["$tok"]=1
        done
    done
fi

# Any fetched object dir is enough to make a rank-1 miss a real miss.
any_fetched=0
for d in "${objects[@]:1}"; do
    if git -C "$d" rev-parse --git-dir >/dev/null 2>&1; then any_fetched=1; fi
done
# The superproject always answers, so a lone `.` in the set is still "fetched".
if [ "${#objects[@]}" -eq 1 ] && git -C . rev-parse --git-dir >/dev/null 2>&1; then
    any_fetched=1
fi

declare -A ghseen
# answer <N> — success when EasyIME/PIME holds issue or PR <N>.
answer() {
    local n=$1 rc
    if [ -n "${ghseen[$n]+x}" ]; then
        return "${ghseen[$n]}"
    fi
    if [ "$(gh api "repos/EasyIME/PIME/issues/$n" --jq .number 2>/dev/null)" = "$n" ]; then
        rc=0
    else
        rc=1
    fi
    ghseen[$n]=$rc
    return "$rc"
}

shas=0 numbers=0 unchecked=0 bad=0
while IFS=$'\t' read -r ticket tok; do
    [ -n "${tok:-}" ] || continue
    # Rank 1: a hex SHA, told from a bare count by its letters.
    if [ -n "${is_sha[$tok]:-}" ]; then
        shas=$((shas + 1))
        if [ -n "${held[$tok]:-}" ]; then
            continue
        fi
        if [ "$any_fetched" -eq 0 ]; then
            printf 'unchecked  %s: %s (no object directory fetched)\n' "$ticket" "$tok"
            unchecked=$((unchecked + 1))
            continue
        fi
        # A 40-char digest in a ticket that names its own kind is a measured value,
        # not a ref: `sha1sum` output has no object in any of these trees.
        if [ "${#tok}" -eq 40 ] && grep -q 'sha1' "$ticket"; then
            printf 'unchecked  %s: %s (content digest, not a ref)\n' "$ticket" "$tok"
            unchecked=$((unchecked + 1))
            continue
        fi
        printf 'BROKEN   %s: %s is no commit in this checkout\n' "$ticket" "$tok"
        # A PR head is the usual reason: only the branches and the PR refs this
        # checkout fetched are objects here, so an unfetched head reads as a dead
        # SHA rather than a missing fetch. The ticket names the PR beside it.
        pr_hint=$(grep -m1 -oE '#[0-9]+' "$ticket" | head -1)
        if [ -n "$pr_hint" ]; then
            printf '         a PR head is often simply unfetched: git fetch upstream refs/pull/%s/head\n' \
                "${pr_hint#\#}"
        fi
        bad=$((bad + 1))
        continue
    fi
    # Rank 2: an explicit `#N` reference, the form the close-out comments use.
    if [[ "$tok" =~ ^#[0-9]+$ ]]; then
        numbers=$((numbers + 1))
        if [ "$have_gh" -eq 0 ] || ! answer "${tok#\#}"; then
            unchecked=$((unchecked + 1))
        fi
        continue
    fi
    # Rank 3: a bare digit string is ambiguous by shape, so any one home counts and
    # the lookup stays local — a miss is simply unchecked.
    if [ -n "${is_num[$tok]:-}" ]; then
        numbers=$((numbers + 1))
        if [ -z "${held[$tok]:-}" ]; then
            unchecked=$((unchecked + 1))
        fi
    fi
done <<< "$pairs"

printf 'checked %d identifier(s) in %d ticket(s): %d commit SHA, %d issue/PR, %d unchecked\n' \
    $((shas + numbers)) "${#tickets[@]}" "$shas" "$numbers" "$unchecked"
if [ "$bad" -gt 0 ]; then
    printf '%d SHA(s) do not resolve\n' "$bad"
    exit 1
fi
exit 0

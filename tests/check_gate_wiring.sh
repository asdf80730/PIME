#!/usr/bin/env bash
# Every `tests/check_*.sh` gate and every `tests/check_*_test.sh` self-test has to
# be named by both local gates — `tests/run_local_tests.sh` (Linux) and
# `tests/verify_windows.sh` (Windows). A check that exists but no gate runs is
# decorative: the 2026-11 rounds twice found a new `check_*.sh` sitting next to its
# wired sibling, green in the folder and absent from the step list.
#
# One awk process reads the two gate files and every check script, then grows a
# reach set per side: a name a gate prints counts, and so does one printed by a
# script already reached on that side — a self-test invokes its own check, so that
# hop must carry. The reference form does not matter (`"$ROOT/tests/x.sh"`,
# `bash.exe tests/x.sh`, or `bash tests/x.sh` all count), only that the name
# appears.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later
#
# Exit codes: 0 every check script is wired, 1 one is unwired,
# 125 not applicable (not inside a git checkout, or no check script present).

set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    printf 'SKIP  gate wiring (not inside a git checkout)\n'
    exit 125
}
cd "$ROOT" || exit 1

GATE_LINUX="tests/run_local_tests.sh"
GATE_WINDOWS="tests/verify_windows.sh"
for gate in "$GATE_LINUX" "$GATE_WINDOWS"; do
    if [ ! -f "$gate" ]; then
        printf 'SKIP  gate wiring (%s missing)\n' "$gate"
        exit 125
    fi
done

mapfile -t scripts < <(git ls-files -- 'tests/check_*.sh' | sort)
[ "${#scripts[@]}" -gt 0 ] || {
    printf 'SKIP  gate wiring (no tests/check_*.sh in this tree)\n'
    exit 125
}

awk '
FILENAME == ARGV[1] { text["linux"] = text["linux"] $0 "\n"; next }
FILENAME == ARGV[2] { text["win"] = text["win"] $0 "\n"; next }
{ text[FILENAME] = text[FILENAME] $0 "\n" }
END {
    n = ARGC - 3
    if (n <= 0) {
        print "SKIP  gate wiring (no tests/check_*.sh in this tree)"
        exit 125
    }
    for (i = 1; i <= n; i++) {
        s = ARGV[2 + i]
        stripped = s
        sub(/^tests\//, "", stripped)
        name[i] = stripped
        full[stripped] = s
    }
    gate["linux"] = ARGV[1]
    gate["win"] = ARGV[2]
    # A script is wired on a side when the gate names it, or when a file already
    # reached on that side does — a self-test invokes its own check, so that hop
    # must carry. Grown to a fixed point.
    sides[1] = "linux"
    sides[2] = "win"
    for (k = 1; k <= 2; k++) {
        g = sides[k]
        known[g, g] = 1
        again = 1
        while (again) {
            again = 0
            for (i = 1; i <= n; i++) {
                s = name[i]
                if ((g, s) in known) continue
                if (index(text[g], s) > 0) { known[g, s] = 1; again = 1 }
                for (j = 1; j <= n; j++) {
                    if (!((g, name[j]) in known)) continue
                    if (index(text[full[name[j]]], s) > 0) { known[g, s] = 1; again = 1 }
                }
            }
        }
        for (i = 1; i <= n; i++) {
            if (!((g, name[i]) in known)) {
                printf "unwired in %s: tests/%s\n", gate[g], name[i]
                bad = 1
            }
        }
    }
    if (bad) exit 1
    printf "wired %d check script(s) in both gates\n", n
}
' "$GATE_LINUX" "$GATE_WINDOWS" "${scripts[@]}"

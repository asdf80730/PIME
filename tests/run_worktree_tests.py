"""Run named backend tests against a sibling worktree's python/ tree so a
PR worktree's product code is exercised from the integration checkout
(docs/agents/upstream-pr.md). Fails outright when cinbase does not bind from
the worktree: a test run against the wrong tree is worse than a red one.

Fully generated by omp (Qwen3.8-Flash-Next) without human intervention."""
import os
import sys
import unittest

if len(sys.argv) < 3:
    print('usage: run_worktree_tests.py <test-file> <worktree-python-parent>', file=sys.stderr)
    raise SystemExit(2)

test_file = os.path.abspath(sys.argv[1])
worktree = os.path.abspath(sys.argv[2])
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
wp = os.path.join(worktree, 'python')
if not os.path.isdir(wp):
    wp = worktree
sys.path.insert(0, root)
sys.path.insert(0, os.path.join(root, 'tests'))
sys.path.insert(0, wp)
# A test can live only in the worktree (one the PR itself ships); discover it
# from its own directory so that invocation binds too.
sys.path.insert(0, os.path.dirname(test_file))
# Test modules re-insert the integration python/ at position 0 on import, so
# cinbase must already sit in sys.modules from the worktree by then.
# The shipped interpreter's _pth also reaches the integration python/, so
# wp must genuinely carry the package or the import below can bind elsewhere.
if not os.path.isdir(os.path.join(wp, 'cinbase')):
    print('ABORT: no cinbase package under %s' % wp, file=sys.stderr)
    raise SystemExit(3)
import cinbase  # noqa: E402,F401 - binds the worktree package first
if not os.path.abspath(cinbase.__file__).startswith(os.path.abspath(wp) + os.sep):
    print('ABORT: cinbase bound from outside %s' % wp, file=sys.stderr)
    raise SystemExit(3)
print('cinbase bound from:', cinbase.__file__)
suite = unittest.defaultTestLoader.loadTestsFromNames(
    [os.path.splitext(os.path.basename(test_file))[0]])
sys.exit(0 if unittest.TextTestRunner(verbosity=2).run(suite).wasSuccessful() else 1)

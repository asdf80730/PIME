#!/usr/bin/env bash
# Run one command inside the vendored .tools/ environment on a Windows checkout.
#
# Git Bash cannot exec .tools/**/*.exe directly (rc=127), and CreateProcess
# cannot search a colon-separated PATH, so the command runs through a
# generated .bat that sets the tool directories in Windows form — the
# write_step pattern of tests/verify_windows.sh, exposed for one-off narrow
# checks without the full suite.
#
# Usage: bash tests/run_windows_tool.sh [<subdir>] <command...>
#   bash tests/run_windows_tool.sh go-backend 'go.exe test ./...'
#   bash tests/run_windows_tool.sh 'gofmt.exe -l .'
# The first argument is a repo-relative subdirectory when that directory
# exists. The command's exit code is the script's. .tools/ lives in the main
# checkout, so this also works from linked worktrees; override the search
# path with PIME_TOOLS=/path/to/.tools.
#
# Generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
# SPDX-License-Identifier: LGPL-2.1-or-later

set -u

if [ "$#" -lt 1 ]; then
	printf 'usage: %s [<subdir>] <command...>\n' "$0" >&2
	exit 2
fi

root=$(git rev-parse --show-toplevel)
common=$(cd "$(git rev-parse --git-common-dir)" && pwd)
main=${common%/.git}
tools=${PIME_TOOLS:-$main/.tools}
if [ ! -d "$tools/go/bin" ]; then
	printf 'no toolchain at %s — run tests/install_windows_toolchain.sh on the main checkout\n' "$tools" >&2
	exit 2
fi

if [ "$#" -ge 2 ] && [ -d "$root/$1" ]; then
	cwd=$1
	shift
else
	cwd=.
fi
command="$*"

win_tools=$(cygpath -w "$tools")
if [ "$cwd" = . ]; then win_cwd=$(cygpath -w "$root"); else win_cwd=$(cygpath -w "$root/$cwd"); fi
bat="${TMPDIR:-/tmp}/pime-win-tool.$$.bat"
trap 'rm -f "$bat"' EXIT
{
	printf '%s\r\n' '@echo off'
	printf '%s\r\n' "set \"PATH=$win_tools\\mingw64\\bin;$win_tools\\go\\bin;$win_tools\\bun;$win_tools\\node;$win_tools\\cargo\\bin;$win_tools\\bin;%PATH%\""
	printf '%s\r\n' "set \"GOROOT=$win_tools\\go\""
	printf '%s\r\n' "set \"GOPATH=$win_tools\\gopath\""
	printf '%s\r\n' "set \"CARGO_HOME=$win_tools\\cargo\""
	printf '%s\r\n' "set \"RUSTUP_HOME=$win_tools\\rustup\""
	printf '%s\r\n' "set \"CARGO_TARGET_DIR=$win_tools\\cargo-target\""
	printf '%s\r\n' "cd /d \"$win_cwd\""
	printf '%s\r\n' "$command"
} >"$bat"
# Direct exec of the .bat propagates the exit code; cmd.exe /c from inside a
# child script drops its argument on this shell (measured 2026-10-27).
"$bat"
